package gen

import (
	"os"
	"os/exec"
	"path/filepath"
	"slices"
	"testing"
)

func repo(t *testing.T) string {
	t.Helper()
	if _, err := exec.LookPath("git"); err != nil {
		t.Skip("no git")
	}
	root := t.TempDir()
	for _, args := range [][]string{{"init", "-q"}} {
		if out, err := exec.Command("git", append([]string{"-C", root}, args...)...).CombinedOutput(); err != nil {
			t.Fatalf("%s", out)
		}
	}
	return root
}

func write(t *testing.T, root, rel, body string) {
	t.Helper()
	p := filepath.Join(root, rel)
	if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(p, []byte(body), 0o644); err != nil {
		t.Fatal(err)
	}
}

func commit(t *testing.T, root string) {
	t.Helper()
	for _, args := range [][]string{{"add", "-A"}, {"-c", "user.email=t@t", "-c", "user.name=t", "commit", "-qm", "x"}} {
		if out, err := exec.Command("git", append([]string{"-C", root}, args...)...).CombinedOutput(); err != nil {
			t.Fatalf("%s", out)
		}
	}
}

// --check sees a regenerated file, a new one the old diff-of-tracked-files missed, a removed one, and a hand edit the
// run put back - and leaves out a file that was already dirty before the run and that the run didn't touch
func TestCheckSeesWhatTheRunChanged(t *testing.T) {
	root := repo(t)
	write(t, root, "docs/permissions.md", "v1\n")
	write(t, root, "apps/backend/core/graph/admin/generated.go", "v1\n")
	write(t, root, "docs/settings.md", "v1\n")
	write(t, root, "docs/webhooks.md", "v1\n")
	write(t, root, "README.md", "not generated\n")
	commit(t, root)
	write(t, root, "docs/settings.md", "dirty before the run\n")
	write(t, root, "docs/webhooks.md", "edited by hand\n")

	before := snapshot(root)
	write(t, root, "docs/permissions.md", "v2\n")
	write(t, root, "apps/backend/core/signalsapi/v1/new.pb.go", "brand new\n")
	_ = os.Remove(filepath.Join(root, "apps/backend/core/graph/admin/generated.go"))
	write(t, root, "README.md", "changed, but not generated\n")
	write(t, root, "docs/webhooks.md", "v1\n")
	got := changed(before, snapshot(root))
	want := []string{"apps/backend/core/graph/admin/generated.go", "apps/backend/core/signalsapi/v1/new.pb.go", "docs/permissions.md", "docs/webhooks.md"}
	if !slices.Equal(got, want) {
		t.Errorf("changed %v\nwant %v", got, want)
	}
	if again := changed(snapshot(root), snapshot(root)); len(again) != 0 {
		t.Errorf("an idle run changed %v", again)
	}
}

func TestClearSqlcRemovesOnlyItsOwnFiles(t *testing.T) {
	root := t.TempDir()
	write(t, root, "apps/backend/core/internal/db/sqlc/orders.sql.go", "// Code generated by sqlc. DO NOT EDIT.\npackage sqlc\n")
	write(t, root, "apps/backend/signals/internal/db/sqlc/models.go", "// Code generated by sqlc. DO NOT EDIT.\npackage sqlc\n")
	write(t, root, "apps/backend/core/internal/db/sqlc/handwritten.go", "package sqlc\n")
	if err := clearSqlc(root); err != nil {
		t.Fatal(err)
	}
	left, _ := filepath.Glob(filepath.Join(root, "apps/backend/*/internal/db/sqlc/*.go"))
	if len(left) != 1 || filepath.Base(left[0]) != "handwritten.go" {
		t.Errorf("left %v", left)
	}
}

