package gen

import (
	"bytes"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"github.com/skeletg/skelet/cmd/skelet/internal/plugins"
	"github.com/skeletg/skelet/cmd/skelet/internal/storefronts"
)

// Where the dashboard and a storefront import their plugins' packages from - each loaded at startup by the app's
// own plugin loader, so the enabled set decides what loads, as plugins/firstparty does for the backend
const (
	dashboardPackages  = "apps/dashboard/src/plugins/packages.ts"
	storefrontLoader   = "app/plugins/loaded.ts"
	storefrontPackages = "app/plugins/packages.ts"
)

// pluginUI writes the import lists of the enabled plugins' dashboard and storefront packages
func pluginUI(root string) error {
	set, _, err := plugins.Load(root)
	if err != nil {
		return err
	}
	slugs := make([]string, 0, len(set.Plugins))
	for slug := range set.Plugins {
		slugs = append(slugs, slug)
	}
	sort.Strings(slugs)
	var dashboard, storefront []string
	for _, slug := range slugs {
		e := set.Plugins[slug]
		if !e.Enabled {
			continue
		}
		if e.Dashboard != "" {
			dashboard = append(dashboard, PackageName(e.Dashboard))
		}
		if e.Storefront != "" {
			storefront = append(storefront, PackageName(e.Storefront))
		}
	}
	if _, err := os.Stat(filepath.Join(root, "apps", "dashboard")); err == nil {
		if err := writeIfChanged(filepath.Join(root, dashboardPackages), importList(dashboard, "'", "")); err != nil {
			return err
		}
	}
	// A storefront without the plugin loader, like the Astro template, draws no plugin UI to load
	for _, sf := range storefronts.List(root) {
		dir := filepath.Join(root, filepath.FromSlash(sf.Dir))
		if _, err := os.Stat(filepath.Join(dir, storefrontLoader)); err != nil {
			continue
		}
		if err := writeIfChanged(filepath.Join(dir, storefrontPackages), importList(storefront, `"`, ";")); err != nil {
			return err
		}
	}
	return nil
}

// PackageName is a package spec without its version - "@acme/fraud-dashboard@^1.2.0" is "@acme/fraud-dashboard"
func PackageName(spec string) string {
	if i := strings.LastIndex(spec, "@"); i > 0 {
		return spec[:i]
	}
	return spec
}

// In each app's own quoting, so the file reads like its neighbours
func importList(pkgs []string, quote, semi string) []byte {
	var b bytes.Buffer
	b.WriteString("// Code generated by skelet gen from plugins.json. DO NOT EDIT.\n")
	b.WriteString("//\n")
	b.WriteString("// The enabled plugins' packages, imported for the registrations they make - skelet plugin add records them\n")
	for _, p := range pkgs {
		fmt.Fprintf(&b, "import %s%s%s%s\n", quote, p, quote, semi)
	}
	fmt.Fprintf(&b, "\nexport {}%s\n", semi)
	return b.Bytes()
}

func writeIfChanged(path string, data []byte) error {
	if old, err := os.ReadFile(path); err == nil && bytes.Equal(old, data) {
		return nil
	}
	return os.WriteFile(path, data, 0o644)
}
