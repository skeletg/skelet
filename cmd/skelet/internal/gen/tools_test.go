func calls(d *verbtest.Docker) []string {
	var out []string
	for _, c := range d.Calls() {
		args, _, _ := strings.Cut(c, "|")
		if !strings.HasPrefix(args, "info ") {
			out = append(out, args)
		}
	}
	return out
}

const user = "-e LC_ALL=C.UTF-8 -e LANG=C.UTF-8"

// sqlc runs as you, so the files it writes into the bind mount are yours and not root's
func TestSqlc(t *testing.T) {
	t.Setenv("SKELET_UID", "")
	t.Setenv("SKELET_NO_USER_MAP", "")
	root := t.TempDir()
	me := "-u " + strconv.Itoa(os.Getuid()) + ":" + strconv.Itoa(os.Getgid())
	mount := "-v " + filepath.Join(root, "apps") + ":/src"
	d := verbtest.NewDocker(t, "")
	out, code := d.Run("sqlc", root)
	want := []string{
		"run --rm " + me + " " + user + " " + mount + " -w /src/backend/core sqlc/sqlc:1.31.1 generate",
		"run --rm " + me + " " + user + " " + mount + " -w /src/backend/signals sqlc/sqlc:1.31.1 generate",
	}
	if code != 0 || strings.Join(calls(d), "\n") != strings.Join(want, "\n") || !strings.Contains(out, "==> sqlc generate (backend/signals)") {
		t.Errorf("exit %d, calls\n%s\nwant\n%s", code, strings.Join(calls(d), "\n"), strings.Join(want, "\n"))
	}
	// generate clears sqlc's own outputs first, so a deleted query's file goes too - and nothing else in the directory
	write(t, root, "apps/backend/core/internal/db/sqlc/gone.sql.go", "// Code generated by sqlc. DO NOT EDIT.\npackage sqlc\n")
	write(t, root, "apps/backend/core/internal/db/sqlc/helpers.go", "package sqlc\n")
	if _, code := d.Run("sqlc", root, "generate"); code != 0 {
		t.Fatalf("exit %d", code)
	}
	if _, err := os.Stat(filepath.Join(root, "apps/backend/core/internal/db/sqlc/gone.sql.go")); !os.IsNotExist(err) {
		t.Error("a stale generated file survived generate")
	}
	if _, err := os.Stat(filepath.Join(root, "apps/backend/core/internal/db/sqlc/helpers.go")); err != nil {
		t.Error("generate removed a hand-written file")
	}
	write(t, root, "apps/backend/core/internal/db/sqlc/gone.sql.go", "// Code generated by sqlc. DO NOT EDIT.\npackage sqlc\n")
	if _, code := d.Run("sqlc", root, "vet"); code != 0 {
		t.Fatalf("exit %d", code)
	}
	if _, err := os.Stat(filepath.Join(root, "apps/backend/core/internal/db/sqlc/gone.sql.go")); err != nil {
		t.Error("vet removed a generated file")
	}
	// A failing module stops there, with sqlc's code
	failing := verbtest.NewDocker(t, "exit 3")
	if _, code := failing.Run("sqlc", root, "vet"); code != 3 || len(calls(failing)) != 1 || !strings.HasSuffix(calls(failing)[0], " vet") {
		t.Errorf("failing: exit %d, calls %q", code, calls(failing))
	}
	// SKELET_NO_USER_MAP runs it as root, the way it does everything else
	t.Setenv("SKELET_NO_USER_MAP", "1")
	root0 := verbtest.NewDocker(t, "")
	if _, code := root0.Run("sqlc", root); code != 0 || !strings.HasPrefix(calls(root0)[0], "run --rm -u 0:0 "+user+" -v") {
		t.Errorf("no user map: exit %d, calls %q", code, calls(root0))
	}
}

const appRunning = `case "$*" in "compose ps --services --status running") echo app ;; esac`

func TestGqlgen(t *testing.T) {
	tool := " app go tool github.com/99designs/gqlgen generate --config gqlgen."
	d := verbtest.NewDocker(t, appRunning)
	if _, code := d.Run("gqlgen", t.TempDir()); code != 0 || strings.Join(calls(d), "\n") !=
		"compose ps --services --status running\ncompose exec "+user+tool+"admin.yml\n"+
			"compose ps --services --status running\ncompose exec "+user+tool+"front.yml" {
		t.Errorf("both: exit %d, calls %q", code, calls(d))
	}
	down := verbtest.NewDocker(t, "")
	if _, code := down.Run("gqlgen", t.TempDir(), "generate", "--config", "gqlgen.front.yml"); code != 0 ||
		calls(down)[len(calls(down))-1] != "compose run --rm --no-deps "+user+tool+"front.yml" {
		t.Errorf("one: exit %d, calls %q", code, calls(down))
	}
}

func TestBuf(t *testing.T) {
	d := verbtest.NewDocker(t, appRunning)
	if _, code := d.Run("buf", t.TempDir()); code != 0 {
		t.Fatalf("exit %d", code)
	}
	// The script spans lines, so the log is read whole
	log := strings.Join(d.Calls(), "\n")
	lint := strings.Index(log, "compose exec "+user+" app sh -c set -e")
	gen := strings.Index(log, `"$@" buf generate --template /var/www/proto/buf.gen.yaml /var/www/proto|`)
	if lint < 0 || gen < 0 || !strings.Contains(log[lint:gen], `"$@" buf lint /var/www/proto|`) {
		t.Errorf("lint, then generate:\n%s", log)
	}
	// Arguments reach buf as arguments - spliced into the script's text, this one would run a second command
	root := t.TempDir()
	argv := verbtest.NewDocker(t, appRunning+`
case "$*" in *"sh -c"*) printf '%s\n' "$@" > "$VERBTEST_ROOT/argv" ;; esac`)
	if _, code := argv.Run("buf", root, "breaking", "a b; touch pwned"); code != 0 {
		t.Fatalf("exit %d", code)
	}
	raw, _ := os.ReadFile(filepath.Join(root, "argv"))
	if !strings.HasSuffix(string(raw), "\"$@\"\nbuf\nbreaking\na b; touch pwned\n") {
		t.Errorf("buf's arguments: %q", raw)
	}
}
