import { fireEvent, screen, waitFor, within } from '@testing-library/react'
import { afterEach, describe, expect, it } from 'vitest'
import type { MockLink } from '@apollo/client/testing'
import { SLOW, meMock, renderPage } from '@/test/page-harness'
import { ChannelsDocument } from '@/features/channels/Channels.gql'
import { UrlRewritesListPage } from './UrlRewritesListPage'
import { AllUrlRewritesDocument, DeleteUrlRewriteDocument } from './Catalog.gql'

// What this pins: deleting a redirect from the list confirms through the shared ConfirmDialog - a refused delete
// keeps it open with the server's message, a successful one closes it

const redirect = {
  __typename: 'UrlRewrite', id: 'r1', entityType: 'PRODUCT', entityId: 'p1', requestPath: '/old-shoe', targetPath: '/shoe', redirectType: 301,
  isAutogenerated: false, description: null, channelId: null, createdAt: '2026-10-01T00:00:00Z', updatedAt: '2026-10-01T00:00:00Z',
}

async function confirmDelete(mock: MockLink.MockedResponse) {
  renderPage({
    path: '/catalog/url-rewrites',
    adminId: 'admin-1',
    routes: { '/catalog/url-rewrites': <UrlRewritesListPage /> },
    mocks: [
      meMock(),
      { request: { query: AllUrlRewritesDocument, variables: () => true }, result: { data: { urlRewrites: { __typename: 'UrlRewritePage', totalCount: 1, items: [redirect] } } }, maxUsageCount: 10 },
      { request: { query: ChannelsDocument }, result: { data: { channels: [] } }, maxUsageCount: 5 },
      mock,
    ],
  })
  // The row menu only renders behind urlrewrite.manage - findBy waits for the grants
  await screen.findByRole('button', { name: 'Actions for /old-shoe' }, SLOW)
  // A late re-render of the row (channels landing) can drop an open menu, so open it until it stays
  await waitFor(() => {
    if (!screen.queryByRole('menuitem', { name: 'Delete' })) {
      fireEvent.pointerDown(screen.getByRole('button', { name: 'Actions for /old-shoe' }), { button: 0, ctrlKey: false })
    }
    expect(screen.getByRole('menuitem', { name: 'Delete' })).toBeDefined()
  }, SLOW)
  fireEvent.click(screen.getByRole('menuitem', { name: 'Delete' }))
  const dialog = await screen.findByRole('alertdialog')
  fireEvent.click(within(dialog).getByRole('button', { name: 'Delete redirect' }))
  return dialog
}

afterEach(() => localStorage.clear())

describe('UrlRewritesListPage delete', () => {
  it('keeps the dialog open and shows a refused delete', async () => {
    const dialog = await confirmDelete({ request: { query: DeleteUrlRewriteDocument, variables: { id: 'r1' } }, result: { errors: [{ message: 'redirect is locked' }] } })
    expect(await within(dialog).findByText('redirect is locked')).toBeDefined()
    expect(screen.getByRole('alertdialog')).toBe(dialog)
  })

  it('closes once the delete goes through', async () => {
    await confirmDelete({ request: { query: DeleteUrlRewriteDocument, variables: { id: 'r1' } }, result: { data: { deleteUrlRewrite: true } } })
    await waitFor(() => expect(screen.queryByRole('alertdialog')).toBeNull())
  })
})
