import { fireEvent, screen, waitFor, within } from '@testing-library/react'
import { describe, expect, it } from 'vitest'
import type { MockLink } from '@apollo/client/testing'
import { renderDialog } from '@/test/page-harness'
import { UrlRewritesSection } from './UrlRewritesSection'
import { DeleteUrlRewriteDocument, UrlRewritesDocument } from './Catalog.gql'

// What this pins: deleting a redirect confirms through the shared ConfirmDialog - a refused delete keeps it open
// with the server's message (it used to land in the section's banner behind the dialog), a successful one closes it

const redirect = {
  __typename: 'UrlRewrite', id: 'r1', requestPath: '/old-shoe', targetPath: '/shoe', redirectType: 301, isAutogenerated: false,
  description: null, channelId: null, createdAt: '2026-10-01T00:00:00Z', updatedAt: '2026-10-01T00:00:00Z',
}
const list = { request: { query: UrlRewritesDocument, variables: { entityType: 'PRODUCT', entityId: 'p1' } }, result: { data: { urlRewrites: { __typename: 'UrlRewritePage', items: [redirect] } } }, maxUsageCount: 5 }

async function confirmDelete(mock: MockLink.MockedResponse) {
  renderDialog(<UrlRewritesSection entityId="p1" canManage />, [list, mock])
  const row = (await screen.findByText('/old-shoe')).closest('.rounded-md.border') as HTMLElement
  fireEvent.click(within(row).getAllByRole('button').at(-1)!)
  const dialog = await screen.findByRole('alertdialog')
  fireEvent.click(within(dialog).getByRole('button', { name: 'Delete redirect' }))
  return dialog
}

describe('UrlRewritesSection delete', () => {
  it('keeps the dialog open and shows a refused delete', async () => {
    const dialog = await confirmDelete({ request: { query: DeleteUrlRewriteDocument, variables: { id: 'r1' } }, result: { errors: [{ message: 'redirect is locked' }] } })
    expect(await within(dialog).findByText('redirect is locked')).toBeDefined()
    expect(screen.getByRole('alertdialog')).toBe(dialog)
  })

  it('closes once the delete goes through', async () => {
    await confirmDelete({ request: { query: DeleteUrlRewriteDocument, variables: { id: 'r1' } }, result: { data: { deleteUrlRewrite: true } } })
    await waitFor(() => expect(screen.queryByRole('alertdialog')).toBeNull())
  })
})
