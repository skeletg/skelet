// Writes the operation names the Apollo split link sends to the Signals API - generated rather than hand-listed, since a name missing here goes silently to core and 404s
import { readFileSync, writeFileSync, readdirSync, statSync } from 'node:fs'
import { join } from 'node:path'

const ROOT = 'src'
const OUT = 'src/graphql/signals-operations.ts'

function walk(dir) {
  return readdirSync(dir).flatMap((entry) => {
    const full = join(dir, entry)
    return statSync(full).isDirectory() ? walk(full) : [full]
  })
}

const names = walk(ROOT)
  .filter((f) => f.endsWith('.signals.graphql'))
  .flatMap((f) => [...readFileSync(f, 'utf8').matchAll(/^\s*(?:query|mutation|subscription)\s+(\w+)/gm)])
  .map((m) => m[1])
  .sort()

const unique = [...new Set(names)]

writeFileSync(
  OUT,
  `// Generated by scripts/signals-operations.mjs - do not edit
// Operation names served by the Signals API rather than the core admin API
export const SIGNALS_OPERATIONS: ReadonlySet<string> = new Set([
${unique.map((n) => `  '${n}',`).join('\n')}
])
`,
)
console.log(`signals-operations: ${unique.length} operation(s) -> ${OUT}`)
