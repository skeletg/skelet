func (r *mutationResolver) CreateURLRewrite(ctx context.Context, input model.CreateURLRewriteInput) (*model.URLRewrite, error) {
	if err := auth.RequireGlobalPermission(ctx, r.AdminSvc, "urlrewrite.manage"); err != nil {
		return nil, err
	}
	entityID, err := uuid.Parse(input.EntityID)
	if err != nil {
		return nil, errInvalidID("entityId", nil)
	}
	rt := urlrewrite.RedirectType(input.RedirectType)
	if !rt.IsValid() {
		return nil, fmt.Errorf("%w: %d", urlrewrite.ErrInvalidRedirectType, input.RedirectType)
	}
	channelID, err := parseOptChannelID(input.ChannelID)
	if err != nil {
		return nil, err
	}
	u, err := r.UrlRewriteSvc.Create(ctx, urlrewrite.CreateInput{
		EntityType:   fromUrlEntityType(input.EntityType),
		EntityID:     entityID,
		RequestPath:  input.RequestPath,
		TargetPath:   input.TargetPath,
		RedirectType: rt,
		Description:  input.Description,
		ChannelID:    channelID,
	})
	if err != nil {
		if errors.Is(err, urlrewrite.ErrPathConflict) {
			return nil, fmt.Errorf("request path is already in use")
		}
		return nil, err
	}
	return toUrlRewriteModel(u), nil
}

func (r *mutationResolver) UpdateURLRewrite(ctx context.Context, input model.UpdateURLRewriteInput) (*model.URLRewrite, error) {
	if err := auth.RequireGlobalPermission(ctx, r.AdminSvc, "urlrewrite.manage"); err != nil {
		return nil, err
	}
	id, err := uuid.Parse(input.ID)
	if err != nil {
		return nil, errInvalidID("id", nil)
	}
	domainInput := urlrewrite.UpdateInput{
		ID:          id,
		RequestPath: input.RequestPath,
		TargetPath:  input.TargetPath,
		Description: input.Description,
	}
	if input.RedirectType != nil {
		rt := urlrewrite.RedirectType(*input.RedirectType)
		domainInput.RedirectType = &rt
	}
	u, err := r.UrlRewriteSvc.Update(ctx, domainInput)
	if err != nil {
		if errors.Is(err, urlrewrite.ErrNotFound) {
			return nil, errNotFound("url rewrite")
		}
		if errors.Is(err, urlrewrite.ErrPathConflict) {
			return nil, fmt.Errorf("request path is already in use")
		}
		if errors.Is(err, urlrewrite.ErrCannotDeleteAutogenerated) {
			return nil, fmt.Errorf("cannot modify autogenerated canonical url rewrite")
		}
		return nil, err
	}
	return toUrlRewriteModel(u), nil
}

func (r *mutationResolver) DeleteURLRewrite(ctx context.Context, id string) (bool, error) {
	if err := auth.RequireGlobalPermission(ctx, r.AdminSvc, "urlrewrite.manage"); err != nil {
		return false, err
	}
	uid, err := uuid.Parse(id)
	if err != nil {
		return false, errInvalidID("id", nil)
	}
	if err := r.UrlRewriteSvc.Delete(ctx, uid); err != nil {
		if errors.Is(err, urlrewrite.ErrNotFound) {
			return false, errNotFound("url rewrite")
		}
		if errors.Is(err, urlrewrite.ErrCannotDeleteAutogenerated) {
			return false, fmt.Errorf("cannot delete autogenerated canonical url rewrite")
		}
		return false, err
	}
	return true, nil
}

// entityType is a free-form slug, not a closed enum, so external services can register their own types without a Skelet schema change
// Gated on urlrewrite.manage, which integration tokens are expected to hold - core domains call the service in-process and never reach here
func (r *mutationResolver) SyncCanonicalURLRewrite(ctx context.Context, input model.SyncCanonicalURLRewriteInput) (*model.URLRewrite, error) {
	if err := auth.RequireGlobalPermission(ctx, r.AdminSvc, "urlrewrite.manage"); err != nil {
		return nil, err
	}
	entityID, err := uuid.Parse(input.EntityID)
	if err != nil {
		return nil, errInvalidID("entityId", nil)
	}
	channelID, err := parseOptChannelID(input.ChannelID)
	if err != nil {
		return nil, err
	}
	if err := r.UrlRewriteSvc.SyncCanonicalForChannel(ctx, input.EntityType, entityID, input.RequestPath, channelID); err != nil {
		if errors.Is(err, urlrewrite.ErrPathConflict) {
			return nil, fmt.Errorf("request path is already in use")
		}
		return nil, err
	}
	rows, err := r.UrlRewriteSvc.ListByEntity(ctx, urlrewrite.EntityType(input.EntityType), entityID) // re-read so the response carries persisted id/timestamps
	if err != nil {
		return nil, err
	}
	for _, rw := range rows {
		if rw.RedirectType == urlrewrite.RedirectTypeCanonical && sameOptChannel(rw.ChannelID, channelID) {
			return toUrlRewriteModel(rw), nil
		}
	}
	return nil, fmt.Errorf("canonical row not found after upsert")
}

// Plugins call this on slug change, right after syncCanonicalUrlRewrite with the new path
func (r *mutationResolver) CreateURLRewriteRedirect(ctx context.Context, input model.CreateURLRewriteRedirectInput) (*model.URLRewrite, error) {
	if err := auth.RequireGlobalPermission(ctx, r.AdminSvc, "urlrewrite.manage"); err != nil {
		return nil, err
	}
	entityID, err := uuid.Parse(input.EntityID)
	if err != nil {
		return nil, errInvalidID("entityId", nil)
	}
	if input.RedirectType != 301 && input.RedirectType != 302 {
		return nil, fmt.Errorf("redirectType must be 301 or 302")
	}
	channelID, err := parseOptChannelID(input.ChannelID)
	if err != nil {
		return nil, err
	}
	if err := r.UrlRewriteSvc.CreateManualRedirectForChannel(ctx, input.FromPath, input.EntityType, entityID, int(input.RedirectType), channelID); err != nil {
		if errors.Is(err, urlrewrite.ErrPathConflict) {
			return nil, fmt.Errorf("fromPath is already in use")
		}
		return nil, err
	}
	// ListByEntity because the repo exposes no GetByPath for non-canonical rows
	rows, err := r.UrlRewriteSvc.ListByEntity(ctx, urlrewrite.EntityType(input.EntityType), entityID)
	if err != nil {
		return nil, err
	}
	for _, rw := range rows {
		if rw.RequestPath == input.FromPath && sameOptChannel(rw.ChannelID, channelID) {
			return toUrlRewriteModel(rw), nil
		}
	}
	return nil, fmt.Errorf("redirect row not found after create")
}

// Called on entity delete so the table does not accumulate orphans
func (r *mutationResolver) DeleteURLRewritesForEntity(ctx context.Context, entityType string, entityID string) (int32, error) {
	if err := auth.RequireGlobalPermission(ctx, r.AdminSvc, "urlrewrite.manage"); err != nil {
		return 0, err
	}
	eid, err := uuid.Parse(entityID)
	if err != nil {
		return 0, errInvalidID("entityId", nil)
	}
	// Counted up front because the service wrapper drops the row count DeleteAllForEntity gets back from the repo
	rows, err := r.UrlRewriteSvc.ListByEntity(ctx, urlrewrite.EntityType(entityType), eid)
	if err != nil {
		return 0, err
	}
	if err := r.UrlRewriteSvc.DeleteAllForEntity(ctx, entityType, eid); err != nil {
		return 0, err
	}
	return int32(len(rows)), nil
}

func (r *queryResolver) ResolveURL(ctx context.Context, path string, channelID *string) (*model.URLResolveResult, error) {
	if _, err := auth.RequireActor(ctx); err != nil {
		return nil, err
	}
	cid, err := parseOptChannelID(channelID)
	if err != nil {
		return nil, err
	}
	u, err := r.UrlRewriteSvc.ResolveURLForChannel(ctx, path, cid)
	if err != nil {
		if errors.Is(err, urlrewrite.ErrNotFound) {
			return nil, nil
		}
		return nil, err
	}
	result := &model.URLResolveResult{
		EntityType:   toUrlEntityType(u.EntityType),
		EntityID:     u.EntityID.String(),
		RedirectType: int32(u.RedirectType),
		RedirectTo:   u.TargetPath,
	}
	return result, nil
}

func (r *queryResolver) URLRewrites(ctx context.Context, entityType *model.URLEntityType, entityID *string, channelID *string, search *string, redirectTypes []int32, autogenerated *bool, limit *int32, offset *int32) (*model.URLRewritePage, error) {
	if err := auth.RequireGlobalPermission(ctx, r.AdminSvc, "urlrewrite.view"); err != nil {
		return nil, err
	}
	cid, err := parseOptChannelID(channelID)
	if err != nil {
		return nil, err
	}
	var list []urlrewrite.UrlRewrite
	var total int64
	if entityID != nil {
		uid, parseErr := uuid.Parse(*entityID)
		if parseErr != nil {
			return nil, errInvalidID("entityId", nil)
		}
		if entityType == nil {
			return nil, fmt.Errorf("entityType is required when entityId is provided")
		}
		list, err = r.UrlRewriteSvc.ListByEntity(ctx, fromUrlEntityType(*entityType), uid) // returns every scope's rows, so narrow when a channel filter was given
		if err == nil && cid != nil {
			list = filterByChannel(list, cid)
		}
		total = int64(len(list))
	} else {
		filter := urlrewrite.ListFilter{
			ChannelID:     cid,
			Search:        ptr.Deref(search),
			RedirectTypes: redirectTypes,
			Autogenerated: autogenerated,
			Limit:         int32Or(limit, 50),
			Offset:        int32Or(offset, 0),
		}
		if entityType != nil {
			et := fromUrlEntityType(*entityType)
			filter.EntityType = &et
		}
		list, total, err = r.UrlRewriteSvc.List(ctx, filter)
	}
	if err != nil {
		return nil, err
	}
	out := make([]*model.URLRewrite, len(list))
	for i, u := range list {
		out[i] = toUrlRewriteModel(u)
	}
	return &model.URLRewritePage{TotalCount: int32(total), Items: out}, nil
}

func (r *queryResolver) URLRewrite(ctx context.Context, id string) (*model.URLRewrite, error) {
	if err := auth.RequireGlobalPermission(ctx, r.AdminSvc, "urlrewrite.view"); err != nil {
		return nil, err
	}
	uid, err := uuid.Parse(id)
	if err != nil {
		return nil, errInvalidID("id", nil)
	}
	u, err := r.UrlRewriteSvc.GetByID(ctx, uid)
	if err != nil {
		if errors.Is(err, urlrewrite.ErrNotFound) {
			return nil, nil
		}
		return nil, err
	}
	return toUrlRewriteModel(u), nil
}

// Internal-link targets for the CMS link picker - labels resolve per entity type in batches (see linkable_helpers.go) and fall back to the path
func (r *queryResolver) Linkables(ctx context.Context, search *string, limit *int32) ([]*model.Linkable, error) {
	if err := auth.RequirePermission(ctx, r.AdminSvc, "cms.view"); err != nil {
		return nil, err
	}
	s := ""
	if search != nil {
		s = *search
	}
	var lim int32
	if limit != nil {
		lim = *limit
	}
	rows, err := r.UrlRewriteSvc.SearchCanonical(ctx, s, "", lim)
	if err != nil {
		return nil, err
	}
	return r.buildLinkables(ctx, rows), nil
}
