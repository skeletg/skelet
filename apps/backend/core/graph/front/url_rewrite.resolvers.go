package front

import (
	"context"
	"errors"
	"strings"

	"github.com/skeletg/skelet/apps/backend/core/graph/front/model"
	"github.com/skeletg/skelet/apps/backend/core/internal/urlrewrite"
)

// Null on no match, and the storefront catch-all turns that into a 404; on a 301/302 row the response carries redirectTo + redirectStatusCode and the caller must ignore kind/entityId
func (r *queryResolver) Route(ctx context.Context, path string) (*model.RouteResolution, error) {
	clean := strings.Trim(strings.TrimSpace(path), "/") // every SyncCanonical writer stores the bare no-slash form, but front-end code builds paths with slashes, so accept "/foo/bar", "foo/bar" and "foo/bar/" alike
	if clean == "" {
		return nil, nil
	}
	storeID := channelIDFromContext(ctx)
	if storeID != nil { // channel URL namespace first - a listing can pin its own slug/url_path for the active channel, and that vocabulary beats the global url_rewrites table here
		if pid, err := r.CatalogSvc.ResolveProductIDForChannelPath(ctx, *storeID, clean); err == nil {
			return &model.RouteResolution{
				Kind:     model.RouteKindProduct,
				EntityID: pid.String(),
			}, nil
		}
	}
	row, err := r.URLRewriteSvc.ResolveURLForChannel(ctx, clean, storeID) // a per-channel url_rewrites override beats the global default, and a nil store resolves purely global
	if err != nil {
		if errors.Is(err, urlrewrite.ErrNotFound) {
			return nil, nil
		}
		return nil, err
	}
	res := &model.RouteResolution{
		Kind:       routeKindFromEntity(row.EntityType),
		PluginKind: pluginKindFor(row.EntityType),
		EntityID:   row.EntityID.String(),
	}
	// Target is the explicit target_path when set, else the entity's CURRENT canonical path - autogenerated rename redirects carry no target_path and would otherwise render the old URL in place with a 200, and resolving live also collapses old → … → current chains to one hop
	if row.RedirectType != urlrewrite.RedirectTypeCanonical {
		target := ""
		if row.TargetPath != nil && urlrewrite.ValidTargetPath(*row.TargetPath) { // a stored off-site target is ignored rather than followed
			target = *row.TargetPath
		} else if canon, ok := r.URLRewriteSvc.CanonicalPathForChannel(ctx, row.EntityType, row.EntityID, storeID); ok {
			target = canon
		}
		if target != "" && strings.Trim(target, "/") != clean { // a target equal to the current path would loop - fall through and render instead
			if !strings.HasPrefix(target, "/") {
				target = "/" + target
			}
			code := int32(row.RedirectType)
			res.RedirectTo = &target
			res.RedirectStatusCode = &code
		}
	}
	return res, nil
}
