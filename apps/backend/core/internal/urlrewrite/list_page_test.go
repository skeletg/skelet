package urlrewrite

import (
	"context"
	"testing"
)

type fakeListRepo struct {
	Repository
	saw ListFilter
}

func (f *fakeListRepo) List(_ context.Context, flt ListFilter) ([]UrlRewrite, int64, error) {
	f.saw = flt
	return []UrlRewrite{}, 3, nil
}

func TestListClampsAndTrims(t *testing.T) { // url_rewrites scales with catalog times channels plus rename history, so the clamp is what keeps this a page
	for name, tc := range map[string]struct {
		limit, offset         int32
		wantLimit, wantOffset int32
	}{
		"unset":        {0, 0, 50, 0},
		"negative":     {-1, -1, 50, 0},
		"normal":       {100, 200, 100, 200},
		"over the cap": {9999, 0, 500, 0},
	} {
		repo := &fakeListRepo{}
		s := &Service{repo: repo}
		if _, _, err := s.List(context.Background(), ListFilter{Limit: tc.limit, Offset: tc.offset, Search: "  /tires  "}); err != nil {
			t.Fatalf("%s: %v", name, err)
		}
		if repo.saw.Limit != tc.wantLimit || repo.saw.Offset != tc.wantOffset {
			t.Errorf("%s: repo saw limit=%d offset=%d, want %d/%d", name, repo.saw.Limit, repo.saw.Offset, tc.wantLimit, tc.wantOffset)
		}
		if repo.saw.Search != "/tires" {
			t.Errorf("%s: search = %q, want it trimmed", name, repo.saw.Search)
		}
	}
}

func TestListKeepsTheFacetFilters(t *testing.T) { // redirectTypes includes 0 (canonical), so presence must matter, not value
	repo := &fakeListRepo{}
	s := &Service{repo: repo}
	auto := true
	et := EntityTypeProduct
	_, total, err := s.List(context.Background(), ListFilter{
		EntityType:    &et,
		RedirectTypes: []int32{0},
		Autogenerated: &auto,
		Limit:         10,
	})
	if err != nil {
		t.Fatalf("List: %v", err)
	}
	if total != 3 {
		t.Errorf("total = %d, want the repo's 3", total)
	}
	if len(repo.saw.RedirectTypes) != 1 || repo.saw.RedirectTypes[0] != 0 {
		t.Errorf("redirectTypes = %v, want the canonical-only filter kept", repo.saw.RedirectTypes)
	}
	if repo.saw.Autogenerated == nil || !*repo.saw.Autogenerated {
		t.Errorf("autogenerated = %v, want true kept", repo.saw.Autogenerated)
	}
	if repo.saw.EntityType == nil || *repo.saw.EntityType != EntityTypeProduct {
		t.Errorf("entityType = %v, want product kept", repo.saw.EntityType)
	}
}
