func init() {
	permission.RegisterGroup(permission.Group{
		Slug:      "urlrewrite",
		Name:      "URL rewrites",
		SortOrder: 80,
	})
	permission.Register(permission.Definition{
		Group: "urlrewrite",
		Slug:  "urlrewrite.view",
		Name:  "View URL rewrites",
	})
	// Plugins and microservices registering their own entity types authenticate as integrations and need this slug to call the sync, redirect and delete mutations
	// Core domains bypass it - they call urlrewrite.Service directly in-process, so no permission gate fires
	permission.Register(permission.Definition{
		Group: "urlrewrite",
		Slug:  "urlrewrite.manage",
		Name:  "Manage URL rewrites",
	})
}

type EntityType string

const (
	EntityTypeProduct      EntityType = "product"
	EntityTypeCollection   EntityType = "collection"
	EntityTypeCategory     EntityType = "category"
	EntityTypeBlogPost     EntityType = "blog_post"
	EntityTypeBlogCategory EntityType = "blog_category"
	EntityTypeBlogTag      EntityType = "blog_tag"
	EntityTypeBlogAuthor   EntityType = "blog_author"
	EntityTypeCMSPage      EntityType = "cms_page"
)

type RedirectType int16

const (
	RedirectTypeCanonical RedirectType = 0
	RedirectTypePermanent RedirectType = 301
	RedirectTypeTemporary RedirectType = 302
)

func (r RedirectType) IsValid() bool {
	return r == RedirectTypeCanonical || r == RedirectTypePermanent || r == RedirectTypeTemporary
}

var (
	ErrNotFound                  = errors.New("url rewrite not found")
	ErrPathConflict              = errors.New("request path already in use")
	ErrCannotDeleteAutogenerated = errors.New("cannot delete autogenerated url rewrite")
	ErrInvalidRedirectType       = errors.New("redirect type must be 0, 301, or 302")
	ErrInvalidPath               = errors.New("a request path is a site path without a query, fragment or spaces")
	ErrInvalidTarget             = errors.New("a redirect target must be a path on this site, starting with a single /")
	ErrCanonicalChange           = errors.New("a canonical row can't become a redirect, or a redirect a canonical - canonicals follow the entity")
)

type UrlRewrite struct {
	ID              uuid.UUID
	EntityType      EntityType
	EntityID        uuid.UUID
	RequestPath     string
	TargetPath      *string
	RedirectType    RedirectType
	IsAutogenerated bool
	Description     *string
	// nil is GLOBAL and applies to every channel; non-nil is a per-channel override that wins over the global row for the same request_path
	ChannelID *uuid.UUID
	CreatedAt time.Time
	UpdatedAt time.Time
}

type CreateInput struct {
	EntityType   EntityType
	EntityID     uuid.UUID
	RequestPath  string
	TargetPath   *string
	RedirectType RedirectType
	Description  *string
	ChannelID    *uuid.UUID // nil = global
	// Marks a system-created rename redirect, left behind when an entity's URL auto-moves - these are prunable by the retention reaper, while operator-authored ones are kept indefinitely
	IsAutogenerated bool
}

type UpdateInput struct {
	ID           uuid.UUID
	RequestPath  *string
	TargetPath   *string // nil = clear
	RedirectType *RedirectType
	Description  *string // nil = clear
}

type ListFilter struct {
	EntityType    *EntityType
	ChannelID     *uuid.UUID // nil = no channel filter (all rows)
	Search        string
	RedirectTypes []int32 // empty = all - 0 is canonical, so presence matters, not value
	Autogenerated *bool
	Limit         int32
	Offset        int32
}

// One URL in a catalog sitemap feed - the canonical path for an entity published on the channel, with the fresher of the rewrite and entity timestamps for <lastmod>
type SitemapEntry struct {
	Path      string
	UpdatedAt time.Time
}

type Repository interface {
	// Resolves a path for a channel, where a channel-specific row wins over the global one - pass a nil channelID for pure-global resolution
	GetByRequestPath(ctx context.Context, path string, channelID *uuid.UUID) (UrlRewrite, error)
	// Pages the canonical, published, indexable paths for one catalog entity type on a channel - product, category and collection only
	SitemapEntries(ctx context.Context, entityType EntityType, channelID uuid.UUID, limit, offset int32) ([]SitemapEntry, error)
	// Counts the URLs SitemapEntries would return, for chunking
	SitemapCount(ctx context.Context, entityType EntityType, channelID uuid.UUID) (int64, error)
	GetByID(ctx context.Context, id uuid.UUID) (UrlRewrite, error)
	List(ctx context.Context, filter ListFilter) ([]UrlRewrite, int64, error)
	// Global canonical rows whose request_path matches search, empty for all, capped at limit - backs the link picker
	SearchCanonical(ctx context.Context, search, entityType string, limit int32) ([]UrlRewrite, error)
	ListByEntity(ctx context.Context, entityType EntityType, entityID uuid.UUID) ([]UrlRewrite, error)
	ListByEntityIDs(ctx context.Context, entityType EntityType, entityIDs []uuid.UUID) ([]UrlRewrite, error)
	// Upserts the canonical row for an entity in the given channel scope - a nil channelID is the global canonical
	UpsertCanonical(ctx context.Context, entityType EntityType, entityID uuid.UUID, requestPath string, channelID *uuid.UUID) (UrlRewrite, error)
	Create(ctx context.Context, input CreateInput) (UrlRewrite, error)
	Update(ctx context.Context, input UpdateInput) (UrlRewrite, error)
	Delete(ctx context.Context, id uuid.UUID) error
	DeleteCanonical(ctx context.Context, entityType EntityType, entityID uuid.UUID) error
	// Removes every rewrite for one entity, canonical and redirects, returning the deleted rows so callers can fire per-path cache invalidation
	DeleteAllForEntity(ctx context.Context, entityType EntityType, entityID uuid.UUID) ([]UrlRewrite, error)
	// Deletes system-generated rename redirects older than cutoff - canonicals and operator redirects are left alone
	PruneAutogeneratedRedirects(ctx context.Context, cutoff time.Time) (int64, error)
	WithTx(tx *sql.Tx) Repository
}
