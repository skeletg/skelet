func TestPruneStaleRedirectsNeedsAPositiveWindow(t *testing.T) {
	// A zero window would mean "cutoff = now" and reap every rename redirect ever written, so an
	// unset retention config has to be a no-op instead
	for name, tc := range map[string]struct {
		olderThan time.Duration
		wantRun   bool
	}{
		"unset":    {0, false},
		"negative": {-time.Hour, false},
		"180 days": {180 * 24 * time.Hour, true},
	} {
		t.Run(name, func(t *testing.T) {
			repo := &fakeScopeRepo{}
			n, err := (&Service{repo: repo}).PruneStaleRedirects(context.Background(), tc.olderThan)
			if err != nil {
				t.Fatalf("PruneStaleRedirects: %v", err)
			}
			if repo.pruned != tc.wantRun {
				t.Fatalf("reaper ran = %v, want %v", repo.pruned, tc.wantRun)
			}
			if !tc.wantRun {
				if n != 0 {
					t.Errorf("pruned %d rows without a window", n)
				}
				return
			}
			if drift := time.Since(repo.pruneCutoff.Add(tc.olderThan)); drift > time.Minute || drift < -time.Minute {
				t.Errorf("cutoff %v is not now minus %v", repo.pruneCutoff, tc.olderThan)
			}
		})
	}
}
