func TestAutogeneratedCanonicalsResistEditAndDelete(t *testing.T) {
	// They're derived from the entity's slug, so hand-editing one desyncs the URL from the entity and
	// the next save silently reverts it - autogenerated REDIRECTS stay editable, they're just history
	for name, tc := range map[string]struct {
		row     UrlRewrite
		wantErr bool
	}{
		"autogenerated canonical": {UrlRewrite{IsAutogenerated: true, RedirectType: RedirectTypeCanonical}, true},
		"autogenerated redirect":  {UrlRewrite{IsAutogenerated: true, RedirectType: RedirectTypePermanent}, false},
		"operator canonical":      {UrlRewrite{RedirectType: RedirectTypeCanonical}, false},
	} {
		t.Run(name, func(t *testing.T) {
			id := uuid.New()
			tc.row.ID = id
			repo := &fakeScopeRepo{byID: map[uuid.UUID]UrlRewrite{id: tc.row}}
			s := &Service{repo: repo}
			_, uerr := s.Update(context.Background(), UpdateInput{ID: id})
			derr := s.Delete(context.Background(), id)
			for label, err := range map[string]error{"Update": uerr, "Delete": derr} {
				if tc.wantErr && !errors.Is(err, ErrCannotDeleteAutogenerated) {
					t.Errorf("%s err = %v, want ErrCannotDeleteAutogenerated", label, err)
				}
				if !tc.wantErr && err != nil {
					t.Errorf("%s err = %v, want nil", label, err)
				}
			}
		})
	}
}

func TestDeleteCanonicalForChannelLeavesEveryOtherScopeAlone(t *testing.T) {
	// Dropping a per-channel root override should fall that storefront back to the global canonical,
	// so taking the global row with it would 404 every channel at once
	globalID, chAID, chBID, redirectID := uuid.New(), uuid.New(), uuid.New(), uuid.New()
	rows := []UrlRewrite{
		{ID: globalID, RedirectType: RedirectTypeCanonical},
		{ID: chAID, RedirectType: RedirectTypeCanonical, ChannelID: &chA},
		{ID: chBID, RedirectType: RedirectTypeCanonical, ChannelID: &chB},
		{ID: redirectID, RedirectType: RedirectTypePermanent, ChannelID: &chA},
	}
	repo := &fakeScopeRepo{entityRows: rows}
	s := &Service{repo: repo}
	if err := s.DeleteCanonicalForChannel(context.Background(), string(EntityTypeProduct), uuid.New(), &chA); err != nil {
		t.Fatalf("DeleteCanonicalForChannel: %v", err)
	}
	if len(repo.deleted) != 1 || repo.deleted[0] != chAID {
		t.Fatalf("deleted %v, want only the channel A canonical", repo.deleted)
	}

	repo.deleted = nil
	if err := s.DeleteCanonicalForChannel(context.Background(), string(EntityTypeProduct), uuid.New(), nil); err != nil {
		t.Fatalf("global DeleteCanonicalForChannel: %v", err)
	}
	if len(repo.deleted) != 0 {
		t.Errorf("a nil channel deleted %v; the global canonical is never dropped here", repo.deleted)
	}
}

func TestCacheKeysCannotCollideAcrossScopes(t *testing.T) {
	// A per-channel override and the global default share the request_path, so one key for both would
	// serve channel A's URL to channel B until the TTL ran out
	keys := map[string]string{
		"global":                           cacheGroup("tires") + "|" + cacheKey(nil),
		"channel A":                        cacheGroup("tires") + "|" + cacheKey(&chA),
		"channel B":                        cacheGroup("tires") + "|" + cacheKey(&chB),
		"global, other path":               cacheGroup("reifen") + "|" + cacheKey(nil),
		"a path shaped like a channel key": cacheGroup("c:"+chA.String()+":tires") + "|" + cacheKey(nil),
	}
	seen := map[string]string{}
	for name, key := range keys {
		if prev, dup := seen[key]; dup {
			t.Errorf("%q and %q share cache key %q", prev, name, key)
		}
		seen[key] = name
	}
}

