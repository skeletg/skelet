// Channel scope is where this service gets dangerous: a global row and a per-channel override share a request_path on purpose, so every "is this path taken", "where does this redirect point" and "may I delete this row" answer has to be scope-exact or one storefront starts serving another's URLs

var (
	chA = uuid.MustParse("aaaaaaaa-1111-1111-1111-111111111111")
	chB = uuid.MustParse("bbbbbbbb-2222-2222-2222-222222222222")
)

func scopeKey(channelID *uuid.UUID, path string) string {
	if channelID == nil {
		return "g|" + path
	}
	return channelID.String() + "|" + path
}

type upsertArgs struct {
	entityType  EntityType
	entityID    uuid.UUID
	requestPath string
	channelID   *uuid.UUID
}

// Mirrors the repository's documented scope rule - a channel row wins, else the global one - so the
// service's decisions are observed at the seam instead of inferred from SQL
type fakeScopeRepo struct {
	Repository
	rows       map[string]UrlRewrite
	entityRows []UrlRewrite
	byID       map[uuid.UUID]UrlRewrite
	getErr     error
	listErr    error
	deleteErr  error

	created         []CreateInput
	upserts         []upsertArgs
	deleted         []uuid.UUID
	updated         bool
	sawLimit        int32
	sawOffset       int32
	pruneCutoff     time.Time
	pruned          bool
	entityIDsCalled bool
}

func (f *fakeScopeRepo) GetByRequestPath(_ context.Context, path string, channelID *uuid.UUID) (UrlRewrite, error) {
	if f.getErr != nil {
		return UrlRewrite{}, f.getErr
	}
	if channelID != nil {
		if rw, ok := f.rows[scopeKey(channelID, path)]; ok {
			return rw, nil
		}
	}
	if rw, ok := f.rows[scopeKey(nil, path)]; ok {
		return rw, nil
	}
	return UrlRewrite{}, ErrNotFound
}

func (f *fakeScopeRepo) ListByEntity(context.Context, EntityType, uuid.UUID) ([]UrlRewrite, error) {
	return f.entityRows, f.listErr
}

func (f *fakeScopeRepo) GetByID(_ context.Context, id uuid.UUID) (UrlRewrite, error) {
	rw, ok := f.byID[id]
	if !ok {
		return UrlRewrite{}, ErrNotFound
	}
	return rw, nil
}

func (f *fakeScopeRepo) Create(_ context.Context, in CreateInput) (UrlRewrite, error) {
	f.created = append(f.created, in)
	return UrlRewrite{
		ID: uuid.New(), EntityType: in.EntityType, EntityID: in.EntityID, RequestPath: in.RequestPath,
		RedirectType: in.RedirectType, ChannelID: in.ChannelID, IsAutogenerated: in.IsAutogenerated,
	}, nil
}

func (f *fakeScopeRepo) UpsertCanonical(_ context.Context, et EntityType, eid uuid.UUID, path string, channelID *uuid.UUID) (UrlRewrite, error) {
	f.upserts = append(f.upserts, upsertArgs{entityType: et, entityID: eid, requestPath: path, channelID: channelID})
	return UrlRewrite{ID: uuid.New(), EntityType: et, EntityID: eid, RequestPath: path, ChannelID: channelID}, nil
}

func (f *fakeScopeRepo) Update(_ context.Context, in UpdateInput) (UrlRewrite, error) {
	f.updated = true
	rw := f.byID[in.ID]
	if in.RequestPath != nil {
		rw.RequestPath = *in.RequestPath
	}
	return rw, nil
}

func (f *fakeScopeRepo) Delete(_ context.Context, id uuid.UUID) error {
	if f.deleteErr != nil {
		return f.deleteErr
	}
	f.deleted = append(f.deleted, id)
	return nil
}

func (f *fakeScopeRepo) SitemapEntries(_ context.Context, _ EntityType, _ uuid.UUID, limit, offset int32) ([]SitemapEntry, error) {
	f.sawLimit, f.sawOffset = limit, offset
	return nil, nil
}

func (f *fakeScopeRepo) SearchCanonical(_ context.Context, _, _ string, limit int32) ([]UrlRewrite, error) {
	f.sawLimit = limit
	return nil, nil
}

func (f *fakeScopeRepo) ListByEntityIDs(context.Context, EntityType, []uuid.UUID) ([]UrlRewrite, error) {
	f.entityIDsCalled = true
	return nil, nil
}

func (f *fakeScopeRepo) PruneAutogeneratedRedirects(_ context.Context, cutoff time.Time) (int64, error) {
	f.pruned, f.pruneCutoff = true, cutoff
	return 7, nil
}

func TestPathConflictIsScopeExact(t *testing.T) {
	prod, other := uuid.New(), uuid.New()
	held := func(channelID *uuid.UUID, et EntityType, eid uuid.UUID) map[string]UrlRewrite {
		return map[string]UrlRewrite{scopeKey(channelID, "tires"): {EntityType: et, EntityID: eid, ChannelID: channelID}}
	}
	for name, tc := range map[string]struct {
		rows      map[string]UrlRewrite
		writeChan *uuid.UUID
		want      bool
	}{
		"nobody holds the path":                             {nil, nil, false},
		"another entity holds it globally":                  {held(nil, EntityTypeProduct, other), nil, true},
		"its own global canonical":                          {held(nil, EntityTypeProduct, prod), nil, false},
		"a channel write can't shadow another's global row": {held(nil, EntityTypeProduct, other), &chA, true},
		"a channel write shadows its own global row":        {held(nil, EntityTypeProduct, prod), &chA, false},
		"another entity holds this channel":                 {held(&chA, EntityTypeProduct, other), &chA, true},
		"its own channel override":                          {held(&chA, EntityTypeProduct, prod), &chA, false},
		"another channel holds it":                          {held(&chB, EntityTypeProduct, other), &chA, false},
		"same id but a different entity type":               {held(nil, EntityTypeCategory, prod), nil, true},
	} {
		t.Run(name, func(t *testing.T) {
			s := &Service{repo: &fakeScopeRepo{rows: tc.rows}}
			got, err := s.PathConflictForChannel(context.Background(), "tires", string(EntityTypeProduct), prod, tc.writeChan)
			if err != nil {
				t.Fatalf("PathConflictForChannel: %v", err)
			}
			if got != tc.want {
				t.Errorf("conflict = %v, want %v", got, tc.want)
			}
		})
	}
}

