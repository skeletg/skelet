func TestCanonicalPathPrefersTheChannelRow(t *testing.T) {
	full := []UrlRewrite{
		{RequestPath: "old-tires", RedirectType: RedirectTypePermanent, ChannelID: &chA},
		{RequestPath: "tires", RedirectType: RedirectTypeCanonical},
		{RequestPath: "reifen", RedirectType: RedirectTypeCanonical, ChannelID: &chA},
	}
	onlyRedirects := []UrlRewrite{{RequestPath: "old-tires", RedirectType: RedirectTypePermanent}}
	for name, tc := range map[string]struct {
		rows    []UrlRewrite
		lookup  *uuid.UUID
		listErr error
		want    string
		wantOK  bool
	}{
		"the channel's own canonical wins":    {full, &chA, nil, "reifen", true},
		"an unlisted channel falls to global": {full, &chB, nil, "tires", true},
		"global lookup ignores channel rows":  {full, nil, nil, "tires", true},
		"redirects are never canonical":       {onlyRedirects, nil, nil, "", false},
		"a read failure resolves to nothing":  {full, &chA, errors.New("gone"), "", false},
	} {
		t.Run(name, func(t *testing.T) {
			s := &Service{repo: &fakeScopeRepo{entityRows: tc.rows, listErr: tc.listErr}}
			got, ok := s.CanonicalPathForChannel(context.Background(), EntityTypeProduct, uuid.New(), tc.lookup)
			if got != tc.want || ok != tc.wantOK {
				t.Errorf("canonical = (%q, %v), want (%q, %v)", got, ok, tc.want, tc.wantOK)
			}
		})
	}
}

func TestSyncCanonicalReclaimsOnlyItsOwnStaleRedirect(t *testing.T) {
	// Renamed away and back leaves this entity's own redirect squatting the target path, and the per-scope unique index
	// blocks the canonical until it goes - deleting anyone else's row instead would silently retarget a live URL
	prod, other, stale := uuid.New(), uuid.New(), uuid.New()
	sitting := func(et EntityType, eid uuid.UUID, rt RedirectType, channelID *uuid.UUID) UrlRewrite {
		return UrlRewrite{ID: stale, EntityType: et, EntityID: eid, RequestPath: "tires", RedirectType: rt, ChannelID: channelID}
	}
	for name, tc := range map[string]struct {
		row         UrlRewrite
		rowScope    *uuid.UUID
		syncScope   *uuid.UUID
		wantDeleted bool
	}{
		"its own redirect in the same scope": {sitting(EntityTypeProduct, prod, RedirectTypePermanent, nil), nil, nil, true},
		"its own redirect in its channel":    {sitting(EntityTypeProduct, prod, RedirectTypePermanent, &chA), &chA, &chA, true},
		"another entity's redirect":          {sitting(EntityTypeProduct, other, RedirectTypePermanent, nil), nil, nil, false},
		"another entity type's redirect":     {sitting(EntityTypeCategory, prod, RedirectTypePermanent, nil), nil, nil, false},
		"a canonical row":                    {sitting(EntityTypeProduct, prod, RedirectTypeCanonical, nil), nil, nil, false},
		"its own row but a global one":       {sitting(EntityTypeProduct, prod, RedirectTypePermanent, nil), nil, &chA, false},
	} {
		t.Run(name, func(t *testing.T) {
			repo := &fakeScopeRepo{rows: map[string]UrlRewrite{scopeKey(tc.rowScope, "tires"): tc.row}}
			s := &Service{repo: repo}
			if err := s.SyncCanonicalForChannel(context.Background(), string(EntityTypeProduct), prod, "tires", tc.syncScope); err != nil {
				t.Fatalf("SyncCanonicalForChannel: %v", err)
			}
			if got := len(repo.deleted) == 1; got != tc.wantDeleted {
				t.Errorf("deleted the sitting row = %v, want %v", got, tc.wantDeleted)
			}
			if len(repo.upserts) != 1 {
				t.Fatalf("upserts = %d, want the canonical written exactly once", len(repo.upserts))
			}
			if !sameChannel(repo.upserts[0].channelID, tc.syncScope) {
				t.Errorf("canonical written in scope %v, want %v", repo.upserts[0].channelID, tc.syncScope)
			}
		})
	}
}

func TestSyncCanonicalAbortsWhenTheReclaimFails(t *testing.T) { // upserting anyway would trip the unique index and lose the rename
	prod := uuid.New()
	boom := errors.New("deadlock detected")
	repo := &fakeScopeRepo{
		rows: map[string]UrlRewrite{scopeKey(nil, "tires"): {
			ID: uuid.New(), EntityType: EntityTypeProduct, EntityID: prod, RedirectType: RedirectTypePermanent,
		}},
		deleteErr: boom,
	}
	s := &Service{repo: repo}
	if err := s.SyncCanonicalForChannel(context.Background(), string(EntityTypeProduct), prod, "tires", nil); !errors.Is(err, boom) {
		t.Fatalf("err = %v, want the delete error", err)
	}
	if len(repo.upserts) != 0 {
		t.Error("the canonical was upserted after the reclaim failed")
	}
}

