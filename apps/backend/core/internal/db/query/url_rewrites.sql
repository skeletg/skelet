-- ==================== URL Rewrites ====================

-- name: GetUrlRewriteByRequestPath :one
-- Channel-aware resolution: a channel-specific row (channel_id = $2) wins over the global default (channel_id IS NULL) for the same request_path - NULLS LAST puts the channel row first - pass NULL channel to resolve purely global (admin / no-channel traffic): then only channel_id IS NULL rows match
SELECT * FROM url_rewrites
WHERE request_path = $1
  AND (channel_id = sqlc.narg(channel_id)::uuid OR channel_id IS NULL)
ORDER BY channel_id NULLS LAST
LIMIT 1;

-- name: GetUrlRewriteByID :one
SELECT * FROM url_rewrites WHERE id = $1;

-- name: GetUrlRewritesByEntityID :many
SELECT * FROM url_rewrites
WHERE entity_type = $1 AND entity_id = $2
ORDER BY redirect_type ASC, created_at DESC;

-- name: GetUrlRewritesByEntityIDs :many
SELECT * FROM url_rewrites
WHERE entity_type = sqlc.arg(entity_type)::text
  AND entity_id = ANY(sqlc.arg(entity_ids)::uuid[])
ORDER BY entity_id, redirect_type ASC, created_at DESC;

-- name: UpsertCanonicalUrlRewriteGlobal :one
-- Inserts or updates the GLOBAL canonical (redirect_type=0, channel_id IS NULL)
-- entry for an entity - the conflict arbiter matches url_rewrites_canonical_global_key
INSERT INTO url_rewrites (entity_type, entity_id, request_path, redirect_type, is_autogenerated, channel_id)
VALUES ($1, $2, $3, 0, TRUE, NULL)
ON CONFLICT (entity_type, entity_id) WHERE redirect_type = 0 AND channel_id IS NULL
DO UPDATE SET request_path = EXCLUDED.request_path,
              updated_at   = NOW()
RETURNING *;

-- name: UpsertCanonicalUrlRewriteChannel :one
-- Inserts or updates a per-CHANNEL canonical override - the conflict arbiter
-- matches url_rewrites_canonical_channel_key
INSERT INTO url_rewrites (entity_type, entity_id, request_path, redirect_type, is_autogenerated, channel_id)
VALUES ($1, $2, $3, 0, TRUE, sqlc.arg(channel_id)::uuid)
ON CONFLICT (channel_id, entity_type, entity_id) WHERE redirect_type = 0 AND channel_id IS NOT NULL
DO UPDATE SET request_path = EXCLUDED.request_path,
              updated_at   = NOW()
RETURNING *;

-- name: CreateUrlRewrite :one
INSERT INTO url_rewrites (entity_type, entity_id, request_path, target_path, redirect_type, is_autogenerated, description, channel_id)
VALUES ($1, $2, $3, $4, $5, $6, $7, sqlc.narg(channel_id)::uuid)
RETURNING *;

-- name: UpdateUrlRewrite :one
UPDATE url_rewrites
SET request_path  = COALESCE(sqlc.narg(request_path), request_path),
    target_path   = sqlc.narg(target_path),
    redirect_type = COALESCE(sqlc.narg(redirect_type), redirect_type),
    description   = sqlc.narg(description),
    updated_at    = NOW()
WHERE id = $1
RETURNING *;

-- name: DeleteUrlRewrite :exec
DELETE FROM url_rewrites WHERE id = $1;

-- name: DeleteCanonicalUrlRewrite :exec
DELETE FROM url_rewrites
WHERE entity_type = $1 AND entity_id = $2 AND redirect_type = 0;

-- name: DeleteAllUrlRewritesForEntity :many
-- Drops every rewrite (canonical + any number of 301/302 redirects) for one entity - returns the deleted rows so the service can fire a Changed{Deleted:true} event per path - the cache invalidation + (future) CDN-purge subscriber depend on knowing which paths went away - called from each domain's Delete<Entity> path so the url_rewrites table doesn't accumulate orphans pointing at nonexistent entity ids
DELETE FROM url_rewrites
WHERE entity_type = $1 AND entity_id = $2
RETURNING *;

-- name: ListUrlRewrites :many
-- The admin listing - url_rewrites scales with catalog size times channels plus rename history, so the page is served server-side - the WHERE must stay in lockstep with CountUrlRewrites
SELECT * FROM url_rewrites
WHERE (sqlc.narg(entity_type)::text IS NULL OR entity_type = sqlc.narg(entity_type)::text)
  AND (sqlc.narg(channel_id)::uuid IS NULL OR channel_id = sqlc.narg(channel_id)::uuid)
  AND (sqlc.arg(search)::text = '' OR
       request_path ILIKE '%' || escape_like(sqlc.arg(search)::text) || '%' OR
       target_path ILIKE '%' || escape_like(sqlc.arg(search)::text) || '%')
  AND (sqlc.arg(all_redirect_types)::boolean OR redirect_type = ANY(sqlc.arg(redirect_types)::int[]))
  AND (sqlc.narg(autogenerated)::boolean IS NULL OR is_autogenerated = sqlc.narg(autogenerated)::boolean)
ORDER BY entity_type, entity_id, redirect_type ASC, created_at DESC
LIMIT sqlc.arg(lim) OFFSET sqlc.arg(off);

-- name: CountUrlRewrites :one
SELECT COUNT(*) FROM url_rewrites
WHERE (sqlc.narg(entity_type)::text IS NULL OR entity_type = sqlc.narg(entity_type)::text)
  AND (sqlc.narg(channel_id)::uuid IS NULL OR channel_id = sqlc.narg(channel_id)::uuid)
  AND (sqlc.arg(search)::text = '' OR
       request_path ILIKE '%' || escape_like(sqlc.arg(search)::text) || '%' OR
       target_path ILIKE '%' || escape_like(sqlc.arg(search)::text) || '%')
  AND (sqlc.arg(all_redirect_types)::boolean OR redirect_type = ANY(sqlc.arg(redirect_types)::int[]))
  AND (sqlc.narg(autogenerated)::boolean IS NULL OR is_autogenerated = sqlc.narg(autogenerated)::boolean);

-- name: SearchCanonicalUrlRewrites :many
-- Global canonical rows (the entities' default URLs) matching a path search Backs the CMS internal-link picker (linkables). channel_id IS NULL = the default URL; a stored reference resolves per-channel at render regardless
SELECT * FROM url_rewrites
WHERE redirect_type = 0
  AND channel_id IS NULL
  AND (sqlc.arg(search)::text = '' OR request_path ILIKE '%' || escape_like(sqlc.arg(search)::text) || '%')
  AND (sqlc.arg(entity_type)::text = '' OR entity_type = sqlc.arg(entity_type)::text)
ORDER BY request_path
LIMIT sqlc.arg(row_limit);

-- name: PruneAutogeneratedRedirects :execrows
-- Delete system-generated rename redirects (from URL auto-moves) older than the cutoff - canonicals (redirect_type = 0) and operator-authored redirects (is_autogenerated = false) are never touched
DELETE FROM url_rewrites
WHERE is_autogenerated = TRUE
  AND redirect_type <> 0
  AND created_at < $1;
