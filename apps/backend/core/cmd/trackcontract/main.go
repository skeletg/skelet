// Command trackcontract writes the storefront's half of the tracking contract - the event names core takes, which of
// them a browser may send, the GA4 ecommerce and item shapes, the click ids and the consent cookie's pattern - from the
// Go that enforces them, so a storefront pushing an event is checked by its compiler and skelet check codegen fails on drift
package main

import (
	"fmt"
	"os"
	"reflect"
	"strings"

	"github.com/skeletg/skelet/apps/backend/core/internal/tracking"
	"github.com/skeletg/skelet/apps/backend/core/lib/auth"
	"github.com/skeletg/skelet/apps/backend/sdk"
)

const target = "/packages/storefront-core/track/contract.gen.ts"

func main() {
	root := "../../.."
	if len(os.Args) > 1 {
		root = os.Args[1]
	}
	out, err := render()
	if err != nil {
		fmt.Fprintf(os.Stderr, "trackcontract: %v\n", err)
		os.Exit(1)
	}
	path := root + target
	if was, err := os.ReadFile(path); err == nil && string(was) == out {
		fmt.Printf("trackcontract: %s already current\n", path)
		return
	}
	if err := os.WriteFile(path, []byte(out), 0o644); err != nil {
		fmt.Fprintf(os.Stderr, "trackcontract: %v\n", err)
		os.Exit(1)
	}
	fmt.Printf("trackcontract: wrote %s\n", path)
}

func render() (string, error) {
	var browser []string
	for _, n := range tracking.Events {
		if tracking.BrowserEvent(n) {
			browser = append(browser, n)
		}
	}
	item, err := shape(reflect.TypeFor[sdk.ShopItem]())
	if err != nil {
		return "", err
	}
	ecommerce, err := shape(reflect.TypeFor[sdk.ShopEcommerce]())
	if err != nil {
		return "", err
	}
	var b strings.Builder
	b.WriteString("// Code generated by apps/backend/core/cmd/trackcontract via skelet gen. DO NOT EDIT.\n")
	b.WriteString("// The tracking contract as core enforces it: internal/tracking's event names, sdk.ShopEcommerce and sdk.ShopItem,\n")
	b.WriteString("// and lib/auth's click ids and consent pattern\n\n")
	b.WriteString("// Every event core takes, GA4's names\n")
	fmt.Fprintf(&b, "export const EVENT_NAMES = %s as const;\nexport type EventName = (typeof EVENT_NAMES)[number];\n\n", list(tracking.Events))
	b.WriteString("// What a browser may report - cart changes, purchases and sign-ups come from the server, so core refuses them here\n")
	fmt.Fprintf(&b, "export const BROWSER_EVENT_NAMES = %s as const;\nexport type BrowserEventName = (typeof BROWSER_EVENT_NAMES)[number];\n\n", list(browser))
	fmt.Fprintf(&b, "export type Item = %s;\n\n", item)
	fmt.Fprintf(&b, "export type Ecommerce = %s;\n\n", ecommerce)
	b.WriteString("// The ad click ids core keeps from the X-Click-Ids header\n")
	fmt.Fprintf(&b, "export const CLICK_ID_KEYS = %s as const;\nexport type ClickIdKey = (typeof CLICK_ID_KEYS)[number];\n\n", list(auth.ClickIDKeys))
	b.WriteString("// The consent cookie's value as core parses it\n")
	fmt.Fprintf(&b, "export const CONSENT_PATTERN = /%s/;\n", auth.ConsentValue.String())
	return b.String(), nil
}

func list(names []string) string {
	q := make([]string, len(names))
	for i, n := range names {
		q[i] = fmt.Sprintf("%q", n)
	}
	return "[" + strings.Join(q, ", ") + "]"
}

// shape is a struct's JSON as a TypeScript object type. Only an item's id is required: GA4 asks every item to name
// itself, while currency and value travel only with an event that has a value, and the server fills in the rest
func shape(t reflect.Type) (string, error) {
	var fields []string
	for f := range t.Fields() {
		tag := f.Tag.Get("json")
		name, opts, _ := strings.Cut(tag, ",")
		if name == "" || name == "-" {
			return "", fmt.Errorf("%s.%s has no json name", t.Name(), f.Name)
		}
		ts, err := tsType(f.Type)
		if err != nil {
			return "", fmt.Errorf("%s.%s: %w", t.Name(), f.Name, err)
		}
		optional := "?"
		if name == "item_id" && !strings.Contains(opts, "omitempty") {
			optional = ""
		}
		fields = append(fields, fmt.Sprintf("  %s%s: %s;", name, optional, ts))
	}
	return "{\n" + strings.Join(fields, "\n") + "\n}", nil
}

func tsType(t reflect.Type) (string, error) {
	switch t.Kind() {
	case reflect.Pointer:
		return tsType(t.Elem())
	case reflect.String:
		return "string", nil
	case reflect.Float64, reflect.Int:
		return "number", nil
	case reflect.Slice:
		if t.Elem() == reflect.TypeFor[sdk.ShopItem]() {
			return "Item[]", nil
		}
	}
	return "", fmt.Errorf("no TypeScript type for %s", t)
}
