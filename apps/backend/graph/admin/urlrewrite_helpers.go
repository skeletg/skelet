package admin

import (
	"github.com/google/uuid"
	"github.com/skeletg/skelet/apps/backend/graph/admin/model"
	"github.com/skeletg/skelet/apps/backend/internal/urlrewrite"
)

func toUrlRewriteModel(u urlrewrite.UrlRewrite) *model.URLRewrite {
	et := toUrlEntityType(u.EntityType)
	m := &model.URLRewrite{
		ID:              u.ID.String(),
		EntityType:      et,
		EntityID:        u.EntityID.String(),
		RequestPath:     u.RequestPath,
		TargetPath:      u.TargetPath,
		RedirectType:    int32(u.RedirectType),
		IsAutogenerated: u.IsAutogenerated,
		Description:     u.Description,
		CreatedAt:       u.CreatedAt,
		UpdatedAt:       u.UpdatedAt,
	}
	if u.ChannelID != nil {
		s := u.ChannelID.String()
		m.ChannelID = &s
	}
	return m
}

// parseOptChannelID converts an optional GraphQL channel ID to *uuid.UUID.
// nil/empty → nil (global scope).
func parseOptChannelID(s *string) (*uuid.UUID, error) {
	if s == nil || *s == "" {
		return nil, nil
	}
	id, err := uuid.Parse(*s)
	if err != nil {
		return nil, errInvalidID("channelId", nil)
	}
	return &id, nil
}

// sameOptChannel reports whether two optional channel ids name the same scope.
func sameOptChannel(a, b *uuid.UUID) bool {
	if a == nil || b == nil {
		return a == nil && b == nil
	}
	return *a == *b
}

// filterByChannel keeps only rewrites in the given channel scope.
func filterByChannel(rows []urlrewrite.UrlRewrite, channelID *uuid.UUID) []urlrewrite.UrlRewrite {
	out := rows[:0]
	for _, rw := range rows {
		if sameOptChannel(rw.ChannelID, channelID) {
			out = append(out, rw)
		}
	}
	return out
}

func toUrlEntityType(et urlrewrite.EntityType) model.URLEntityType {
	switch et {
	case urlrewrite.EntityTypeProduct:
		return model.URLEntityTypeProduct
	case urlrewrite.EntityTypeCollection:
		return model.URLEntityTypeCollection
	case urlrewrite.EntityTypeCategory:
		return model.URLEntityTypeCategory
	case urlrewrite.EntityTypeBlogPost:
		return model.URLEntityTypeBlogPost
	case urlrewrite.EntityTypeBlogCategory:
		return model.URLEntityTypeBlogCategory
	case urlrewrite.EntityTypeBlogTag:
		return model.URLEntityTypeBlogTag
	case urlrewrite.EntityTypeBlogAuthor:
		return model.URLEntityTypeBlogAuthor
	case urlrewrite.EntityTypeCMSPage:
		return model.URLEntityTypeCmsPage
	default:
		return model.URLEntityTypeProduct
	}
}

func fromUrlEntityType(et model.URLEntityType) urlrewrite.EntityType {
	switch et {
	case model.URLEntityTypeProduct:
		return urlrewrite.EntityTypeProduct
	case model.URLEntityTypeCollection:
		return urlrewrite.EntityTypeCollection
	case model.URLEntityTypeCategory:
		return urlrewrite.EntityTypeCategory
	case model.URLEntityTypeBlogPost:
		return urlrewrite.EntityTypeBlogPost
	case model.URLEntityTypeBlogCategory:
		return urlrewrite.EntityTypeBlogCategory
	case model.URLEntityTypeBlogTag:
		return urlrewrite.EntityTypeBlogTag
	case model.URLEntityTypeBlogAuthor:
		return urlrewrite.EntityTypeBlogAuthor
	case model.URLEntityTypeCmsPage:
		return urlrewrite.EntityTypeCMSPage
	default:
		return urlrewrite.EntityTypeProduct
	}
}
