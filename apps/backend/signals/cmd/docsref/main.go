// Command docsref fills the generated table in docs/tracking-plan.md from analytics.TrackingPlan, the registry Lens
// ingest enforces - so the published plan is the one the server holds browsers to. Prose around the block stays hand-written
package main

import (
	"fmt"
	"os"
	"sort"
	"strings"

	"github.com/skeletg/skelet/apps/backend/signals/internal/analytics"
)

const (
	begin = "<!-- BEGIN GENERATED TRACKING PLAN -->"
	end   = "<!-- END GENERATED TRACKING PLAN -->"
)

func main() {
	path := "../../../docs/tracking-plan.md"
	if len(os.Args) > 1 {
		path = os.Args[1]
	}
	if err := fill(path); err != nil {
		fmt.Fprintf(os.Stderr, "docsref: %s: %v\n", path, err)
		os.Exit(1)
	}
}

func fill(path string) error {
	raw, err := os.ReadFile(path)
	if err != nil {
		return err
	}
	src := string(raw)
	s, e := strings.Index(src, begin), strings.Index(src, end)
	if s < 0 || e < s {
		return fmt.Errorf("missing the %s / %s markers", begin, end)
	}
	block := begin + "\n<!-- Generated by signals/cmd/docsref via skelet gen. Edits here are overwritten. -->\n\n" + render() + "\n" + end
	out := src[:s] + block + src[e+len(end):]
	if out == src {
		fmt.Printf("docsref: %s already current (%d events)\n", path, len(analytics.TrackingPlan))
		return nil
	}
	if err := os.WriteFile(path, []byte(out), 0o644); err != nil {
		return err
	}
	fmt.Printf("docsref: wrote %d events into %s\n", len(analytics.TrackingPlan), path)
	return nil
}

func render() string {
	var b strings.Builder
	b.WriteString("| Event | What it means | Properties |\n|---|---|---|\n")
	for _, e := range analytics.TrackingPlan {
		keys := make([]string, 0, len(e.Props))
		for k := range e.Props {
			keys = append(keys, k)
		}
		sort.Strings(keys)
		props := make([]string, 0, len(keys)+1)
		for _, k := range keys {
			props = append(props, fmt.Sprintf("`%s` %s", k, e.Props[k]))
		}
		if e.Open {
			props = append(props, "any other string, number or bool")
		}
		if e.Attrs {
			props = append(props, "`attr:<slug>` string")
		}
		list := strings.Join(props, ", ")
		if list == "" {
			list = "none"
		}
		fmt.Fprintf(&b, "| `%s` | %s | %s |\n", e.Name, e.About, list)
	}
	server := append([]string(nil), analytics.ServerProps...)
	sort.Strings(server)
	fmt.Fprintf(&b, "\nSet only by the server, and stripped when a browser sends them: `%s`.\n", strings.Join(server, "`, `"))
	return b.String()
}
