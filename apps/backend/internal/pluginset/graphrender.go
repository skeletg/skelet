package pluginset

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"sort"
	"strings"
	"unicode"
)

const (
	pluginhostPath = "github.com/skeletg/skelet/apps/backend/internal/plugin"
	sdkPath        = "github.com/skeletg/skelet/apps/backend/sdk"
)

// internal/plugin's package name is `plugin`, and the tree refers to it as pluginhost everywhere - so an alias
// is written whenever the name a file uses differs from the import path's last segment
func writeImports(b *bytes.Buffer, need map[string]string) {
	names := make([]string, 0, len(need))
	for n := range need {
		names = append(names, n)
	}
	sort.Strings(names)
	b.WriteString("import (\n")
	for _, n := range names {
		path := need[n]
		if path[strings.LastIndex(path, "/")+1:] == n {
			fmt.Fprintf(b, "\t%q\n", path)
			continue
		}
		fmt.Fprintf(b, "\t%s %q\n", n, path)
	}
	b.WriteString(")\n")
}

// ifaceName is derived from the slug so two plugins can never collide, and so the name never has to be chosen
// by hand - payment-klarna on the front surface is paymentKlarnaFront
func ifaceName(slug, surface string) string {
	parts := strings.FieldsFunc(slug, func(r rune) bool { return r == '-' || r == '_' })
	var b strings.Builder
	for i, p := range parts {
		if p == "" {
			continue
		}
		r := []rune(p)
		if i == 0 {
			r[0] = unicode.ToLower(r[0])
		} else {
			r[0] = unicode.ToUpper(r[0])
		}
		b.WriteString(string(r))
	}
	r := []rune(surface)
	r[0] = unicode.ToUpper(r[0])
	return b.String() + string(r)
}

// The delegation every plugin field routes through - looked up by slug at run time and type-asserted against the
// interface, so core never imports the plugin and the two stay coupled only by shape
func renderResolvers(pkg, sdkConst string, ms []method, avail map[string]string) ([]byte, error) {
	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by cmd/plugingraph. DO NOT EDIT.\n")
	fmt.Fprintf(&b, "//\n")
	fmt.Fprintf(&b, "// Delegation into a plugin's own resolver, reached through the runtime registry rather than an\n")
	fmt.Fprintf(&b, "// import, so a disabled or panicking plugin is a typed error instead of a link-time dependency\n")
	fmt.Fprintf(&b, "// Signatures are gqlgen's, read back from what it generated - edit the SDL, not this file\n\n")
	fmt.Fprintf(&b, "package %s\n\n", pkg)

	need := map[string]string{"pluginhost": pluginhostPath, "sdk": sdkPath}
	for _, m := range ms {
		for _, p := range m.pkgs {
			if path, ok := avail[p]; ok {
				need[p] = path
			}
		}
	}
	writeImports(&b, need)

	for _, m := range ms {
		iface := ifaceName(m.slug, strings.TrimSuffix(pkg, ""))
		fmt.Fprintf(&b, "\n// %s is the resolver for the %s field.\n", m.name, m.field)
		fmt.Fprintf(&b, "func (r *%s) %s(%s) %s {\n", m.recv, m.name, m.params, m.results)
		fmt.Fprintf(&b, "\treturn pluginhost.Do(ctx, %s, %q, %q,\n", sdkConst, m.slug, m.field)
		fmt.Fprintf(&b, "\t\tfunc(ctx context.Context, impl %s) %s {\n", iface, m.results)
		fmt.Fprintf(&b, "\t\t\treturn impl.%s(%s)\n", m.name, m.args)
		fmt.Fprintf(&b, "\t\t})\n")
		fmt.Fprintf(&b, "}\n")
	}
	return format.Source(b.Bytes())
}

// The compile-time half: one structural interface per plugin surface, plus the boot check that a registered
// resolver actually satisfies it - kept out of the .resolvers.go files because gqlgen relocates non-resolver decls
func writePluginResolvers(root, surface, pkg string, ms []method) error {
	path := filepath.Join(root, "graph", surface, "plugin_resolvers.go")
	// Core wiring calls ValidatePluginResolvers unconditionally, so an empty plugin set still has to
	// generate the symbol - a stub that validates nothing, not a missing file
	if len(ms) == 0 {
		var b bytes.Buffer
		fmt.Fprintf(&b, "// Code generated by cmd/plugingraph. DO NOT EDIT.\n\n")
		fmt.Fprintf(&b, "package %s\n\n", pkg)
		fmt.Fprintf(&b, "// No enabled plugin extends this surface - nothing to check at boot\n")
		fmt.Fprintf(&b, "func ValidatePluginResolvers() error { return nil }\n")
		src, err := format.Source(b.Bytes())
		if err != nil {
			return fmt.Errorf("format %s: %w", path, err)
		}
		return os.WriteFile(path, src, 0o644)
	}

	bySlug := map[string][]method{}
	var slugs []string
	for _, m := range ms {
		if _, seen := bySlug[m.slug]; !seen {
			slugs = append(slugs, m.slug)
		}
		bySlug[m.slug] = append(bySlug[m.slug], m)
	}
	sort.Strings(slugs)

	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by cmd/plugingraph. DO NOT EDIT.\n")
	fmt.Fprintf(&b, "//\n")
	fmt.Fprintf(&b, "// Plugins never import these - Go matches them structurally, so core's graph and each plugin stay\n")
	fmt.Fprintf(&b, "// compile-time coupled with no shared type between them\n\n")
	fmt.Fprintf(&b, "package %s\n\n", pkg)

	need := map[string]string{
		"context":    "context",
		"pluginhost": pluginhostPath,
		"sdk":        sdkPath,
	}
	for _, m := range ms {
		for _, p := range m.pkgs {
			if p == "model" {
				need["model"] = fmt.Sprintf("github.com/skeletg/skelet/apps/backend/graph/%s/model", surface)
			}
			if p == "uuid" {
				need["uuid"] = "github.com/google/uuid"
			}
			if p == "time" {
				need["time"] = "time"
			}
		}
	}
	writeImports(&b, need)

	for _, slug := range slugs {
		iface := ifaceName(slug, surface)
		fmt.Fprintf(&b, "\ntype %s interface {\n", iface)
		for _, m := range bySlug[slug] {
			fmt.Fprintf(&b, "\t%s(%s) %s\n", m.name, m.params, m.results)
		}
		fmt.Fprintf(&b, "}\n")
	}

	sdkConst := "sdk.GraphFront"
	if surface == "admin" {
		sdkConst = "sdk.GraphAdmin"
	}
	fmt.Fprintf(&b, "\n// Called at boot - an uninstalled plugin skips, a registered one whose SDL and Go methods have drifted fails loudly\n")
	fmt.Fprintf(&b, "func ValidatePluginResolvers() error {\n")
	fmt.Fprintf(&b, "\tfor _, check := range []func() error{\n")
	for _, slug := range slugs {
		fmt.Fprintf(&b, "\t\tfunc() error { return pluginhost.RequireGraphResolver[%s](%s, %q) },\n", ifaceName(slug, surface), sdkConst, slug)
	}
	fmt.Fprintf(&b, "\t} {\n\t\tif err := check(); err != nil {\n\t\t\treturn err\n\t\t}\n\t}\n\treturn nil\n}\n")

	src, err := format.Source(b.Bytes())
	if err != nil {
		return fmt.Errorf("format %s: %w", path, err)
	}
	return os.WriteFile(path, src, 0o644)
}
