--
-- Lets the flow engine's claim stop early instead of sorting the whole runnable set
--
-- ClaimRunnableFlowRuns takes the oldest runnable runs, but the only index covering the
-- runnable predicate is (status, resume_at), so nothing could satisfy ORDER BY created_at -
-- every tick scanned all live runs and sorted them to take 100, a cost that grows with the
-- table on an engine that runs once a minute
--
-- Partial on the two live statuses, which is what the claim asks for and what keeps the
-- index to the working set rather than every run the store has ever completed
--
CREATE INDEX flow_runs_claim ON public.flow_runs USING btree (created_at) WHERE (status = ANY (ARRAY['active'::text, 'waiting'::text]));
