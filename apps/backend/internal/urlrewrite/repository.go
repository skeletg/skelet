package urlrewrite

import (
	"context"
	"database/sql"
	"errors"
	"fmt"
	"time"

	"github.com/google/uuid"
	pgdb "github.com/skeletg/skelet/internal/db"
	db "github.com/skeletg/skelet/internal/db/sqlc"
)

type postgresRepository struct {
	queries *db.Queries
}

func NewRepository(queries *db.Queries) Repository {
	return &postgresRepository{queries: queries}
}

func (r *postgresRepository) WithTx(tx *sql.Tx) Repository {
	return &postgresRepository{queries: r.queries.WithTx(tx)}
}

func (r *postgresRepository) GetByRequestPath(ctx context.Context, path string, channelID *uuid.UUID) (UrlRewrite, error) {
	row, err := r.queries.GetUrlRewriteByRequestPath(ctx, db.GetUrlRewriteByRequestPathParams{
		RequestPath: path,
		ChannelID:   nullUUID(channelID),
	})
	if err != nil {
		if errors.Is(err, sql.ErrNoRows) {
			return UrlRewrite{}, ErrNotFound
		}
		return UrlRewrite{}, fmt.Errorf("get url rewrite by path: %w", err)
	}
	return toUrlRewrite(row), nil
}

func (r *postgresRepository) SitemapEntries(ctx context.Context, entityType EntityType, channelID uuid.UUID, limit, offset int32) ([]SitemapEntry, error) {
	var (
		out []SitemapEntry
		err error
	)
	switch entityType {
	case EntityTypeProduct:
		var rows []db.SitemapProductPathsRow
		rows, err = r.queries.SitemapProductPaths(ctx, db.SitemapProductPathsParams{ChannelID: channelID, Limit: limit, Offset: offset})
		for _, row := range rows {
			out = append(out, SitemapEntry{Path: row.Path, UpdatedAt: row.UpdatedAt})
		}
	case EntityTypeCategory:
		var rows []db.SitemapCategoryPathsRow
		rows, err = r.queries.SitemapCategoryPaths(ctx, db.SitemapCategoryPathsParams{ChannelID: channelID, Limit: limit, Offset: offset})
		for _, row := range rows {
			out = append(out, SitemapEntry{Path: row.Path, UpdatedAt: row.UpdatedAt})
		}
	case EntityTypeCollection:
		var rows []db.SitemapCollectionPathsRow
		rows, err = r.queries.SitemapCollectionPaths(ctx, db.SitemapCollectionPathsParams{ChannelID: uuid.NullUUID{UUID: channelID, Valid: true}, Limit: limit, Offset: offset})
		for _, row := range rows {
			out = append(out, SitemapEntry{Path: row.Path, UpdatedAt: row.UpdatedAt})
		}
	default:
		return nil, fmt.Errorf("sitemap entries: unsupported entity type %q", entityType)
	}
	if err != nil {
		return nil, fmt.Errorf("sitemap entries (%s): %w", entityType, err)
	}
	return out, nil
}

func (r *postgresRepository) SitemapCount(ctx context.Context, entityType EntityType, channelID uuid.UUID) (int64, error) {
	var (
		n   int64
		err error
	)
	switch entityType {
	case EntityTypeProduct:
		n, err = r.queries.SitemapProductCount(ctx, channelID)
	case EntityTypeCategory:
		n, err = r.queries.SitemapCategoryCount(ctx, channelID)
	case EntityTypeCollection:
		n, err = r.queries.SitemapCollectionCount(ctx, uuid.NullUUID{UUID: channelID, Valid: true})
	default:
		return 0, fmt.Errorf("sitemap count: unsupported entity type %q", entityType)
	}
	if err != nil {
		return 0, fmt.Errorf("sitemap count (%s): %w", entityType, err)
	}
	return n, nil
}

