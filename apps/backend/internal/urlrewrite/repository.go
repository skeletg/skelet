func toUrlRewrite(row db.UrlRewrite) UrlRewrite {
	u := UrlRewrite{
		ID:              row.ID,
		EntityType:      EntityType(row.EntityType),
		EntityID:        row.EntityID,
		RequestPath:     row.RequestPath,
		RedirectType:    RedirectType(row.RedirectType),
		IsAutogenerated: row.IsAutogenerated,
		CreatedAt:       row.CreatedAt,
		UpdatedAt:       row.UpdatedAt,
	}
	if row.TargetPath.Valid {
		u.TargetPath = &row.TargetPath.String
	}
	if row.Description.Valid {
		u.Description = &row.Description.String
	}
	if row.ChannelID.Valid {
		cid := row.ChannelID.UUID
		u.ChannelID = &cid
	}
	return u
}

// nullUUID converts an optional channel id to the sqlc nullable form
func nullBool(p *bool) sql.NullBool {
	if p == nil {
		return sql.NullBool{}
	}
	return sql.NullBool{Bool: *p, Valid: true}
}

func nullUUID(p *uuid.UUID) uuid.NullUUID {
	if p == nil {
		return uuid.NullUUID{}
	}
	return uuid.NullUUID{UUID: *p, Valid: true}
}

func toUrlRewrites(rows []db.UrlRewrite) []UrlRewrite {
	out := make([]UrlRewrite, len(rows))
	for i, row := range rows {
		out[i] = toUrlRewrite(row)
	}
	return out
}

func isUniqueViolation(err error) bool { return pgdb.IsUniqueViolation(err) } // shared SQLSTATE-based check - the per-package copies drifted into fragile message matching

func stringVal(p *string) string {
	if p == nil {
		return ""
	}
	return *p
}
