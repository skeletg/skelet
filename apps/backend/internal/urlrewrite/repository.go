func (r *postgresRepository) UpsertCanonical(ctx context.Context, entityType EntityType, entityID uuid.UUID, requestPath string, channelID *uuid.UUID) (UrlRewrite, error) {
	// Two queries: the conflict arbiter must match exactly one of the partial
	// canonical indexes (global vs channel-scoped)
	var (
		row db.UrlRewrite
		err error
	)
	if channelID == nil {
		row, err = r.queries.UpsertCanonicalUrlRewriteGlobal(ctx, db.UpsertCanonicalUrlRewriteGlobalParams{
			EntityType:  string(entityType),
			EntityID:    entityID,
			RequestPath: requestPath,
		})
	} else {
		row, err = r.queries.UpsertCanonicalUrlRewriteChannel(ctx, db.UpsertCanonicalUrlRewriteChannelParams{
			EntityType:  string(entityType),
			EntityID:    entityID,
			RequestPath: requestPath,
			ChannelID:   *channelID,
		})
	}
	if err != nil {
		if isUniqueViolation(err) {
			return UrlRewrite{}, ErrPathConflict
		}
		return UrlRewrite{}, fmt.Errorf("upsert canonical url rewrite: %w", err)
	}
	return toUrlRewrite(row), nil
}

func (r *postgresRepository) Create(ctx context.Context, input CreateInput) (UrlRewrite, error) {
	row, err := r.queries.CreateUrlRewrite(ctx, db.CreateUrlRewriteParams{
		EntityType:      string(input.EntityType),
		EntityID:        input.EntityID,
		RequestPath:     input.RequestPath,
		TargetPath:      sql.NullString{String: stringVal(input.TargetPath), Valid: input.TargetPath != nil},
		RedirectType:    int16(input.RedirectType),
		IsAutogenerated: input.IsAutogenerated,
		Description:     sql.NullString{String: stringVal(input.Description), Valid: input.Description != nil},
		ChannelID:       nullUUID(input.ChannelID),
	})
	if err != nil {
		if isUniqueViolation(err) {
			return UrlRewrite{}, ErrPathConflict
		}
		return UrlRewrite{}, fmt.Errorf("create url rewrite: %w", err)
	}
	return toUrlRewrite(row), nil
}

func (r *postgresRepository) Update(ctx context.Context, input UpdateInput) (UrlRewrite, error) {
	var redirectType sql.NullInt16
	if input.RedirectType != nil {
		redirectType = sql.NullInt16{Int16: int16(*input.RedirectType), Valid: true}
	}
	row, err := r.queries.UpdateUrlRewrite(ctx, db.UpdateUrlRewriteParams{
		ID:           input.ID,
		RequestPath:  sql.NullString{String: stringVal(input.RequestPath), Valid: input.RequestPath != nil},
		TargetPath:   sql.NullString{String: stringVal(input.TargetPath), Valid: input.TargetPath != nil},
		RedirectType: redirectType,
		Description:  sql.NullString{String: stringVal(input.Description), Valid: input.Description != nil},
	})
	if err != nil {
		if errors.Is(err, sql.ErrNoRows) {
			return UrlRewrite{}, ErrNotFound
		}
		if isUniqueViolation(err) {
			return UrlRewrite{}, ErrPathConflict
		}
		return UrlRewrite{}, fmt.Errorf("update url rewrite: %w", err)
	}
	return toUrlRewrite(row), nil
}

func (r *postgresRepository) Delete(ctx context.Context, id uuid.UUID) error {
	if err := r.queries.DeleteUrlRewrite(ctx, id); err != nil {
		return fmt.Errorf("delete url rewrite: %w", err)
	}
	return nil
}

