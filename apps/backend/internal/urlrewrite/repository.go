func (r *postgresRepository) List(ctx context.Context, filter ListFilter) ([]UrlRewrite, int64, error) {
	var et sql.NullString
	if filter.EntityType != nil {
		et = sql.NullString{String: string(*filter.EntityType), Valid: true}
	}
	rows, err := r.queries.ListUrlRewrites(ctx, db.ListUrlRewritesParams{
		EntityType:       et,
		ChannelID:        nullUUID(filter.ChannelID),
		Search:           filter.Search,
		AllRedirectTypes: len(filter.RedirectTypes) == 0,
		RedirectTypes:    filter.RedirectTypes,
		Autogenerated:    nullBool(filter.Autogenerated),
		Lim:              filter.Limit,
		Off:              filter.Offset,
	})
	if err != nil {
		return nil, 0, fmt.Errorf("list url rewrites: %w", err)
	}
	total, err := r.queries.CountUrlRewrites(ctx, db.CountUrlRewritesParams{
		EntityType:       et,
		ChannelID:        nullUUID(filter.ChannelID),
		Search:           filter.Search,
		AllRedirectTypes: len(filter.RedirectTypes) == 0,
		RedirectTypes:    filter.RedirectTypes,
		Autogenerated:    nullBool(filter.Autogenerated),
	})
	if err != nil {
		return nil, 0, fmt.Errorf("count url rewrites: %w", err)
	}
	return toUrlRewrites(rows), total, nil
}

