package urlrewrite

import "github.com/skeletg/skelet/apps/backend/internal/apperr"

func init() {
	apperr.RegisterSentinel(ErrNotFound, "URL_REWRITE_NOT_FOUND", apperr.ClassNotFound)

	apperr.RegisterSentinel(ErrPathConflict, "URL_PATH_TAKEN", apperr.ClassConflict)
	apperr.RegisterSentinel(ErrCannotDeleteAutogenerated, "URL_REWRITE_AUTOGENERATED", apperr.ClassConflict)

	apperr.RegisterSentinel(ErrInvalidRedirectType, "URL_INVALID_REDIRECT_TYPE", apperr.ClassValidation)
}
