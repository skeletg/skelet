// Command docsref fills the generated reference tables in docs/ from the code-defined
// registries - permissions, webhook events and settings
// Each is declared in a domain package's init(), so importing internal/wiring for its
// transitive side effects is what makes the published list the one the server enforces
// Prose around each block stays hand-written; only the marked region is rewritten
package main

import (
	"fmt"
	"os"
	"sort"
	"strings"

	"github.com/skeletg/skelet/internal/config"
	"github.com/skeletg/skelet/internal/permission"
	"github.com/skeletg/skelet/internal/webhook"
	_ "github.com/skeletg/skelet/internal/wiring"
)

type target struct {
	path   string
	marker string
	render func() (string, int, error)
}

func main() {
	root := "../.."
	if len(os.Args) > 1 {
		root = os.Args[1]
	}
	targets := []target{
		{root + "/docs/permissions.md", "PERMISSIONS", renderPermissions},
		{root + "/docs/webhooks.md", "WEBHOOK EVENTS", renderWebhookEvents},
		{root + "/docs/settings.md", "SETTINGS", renderSettings},
	}
	failed := false
	for _, t := range targets {
		if err := fill(t); err != nil {
			fmt.Fprintf(os.Stderr, "docsref: %s: %v\n", t.path, err)
			failed = true
		}
	}
	if failed {
		os.Exit(1)
	}
}

func fill(t target) error {
	body, n, err := t.render()
	if err != nil {
		return err
	}
	begin := "<!-- BEGIN GENERATED " + t.marker + " -->"
	end := "<!-- END GENERATED " + t.marker + " -->"

	existing, err := os.ReadFile(t.path)
	if err != nil {
		return err
	}
	src := string(existing)
	s, e := strings.Index(src, begin), strings.Index(src, end)
	if s < 0 || e < 0 || e < s {
		return fmt.Errorf("missing the %s / %s markers", begin, end)
	}
	block := begin + "\n<!-- Generated by cmd/docsref via bin/codegen. Edits here are overwritten. -->\n\n" + body + "\n" + end
	out := src[:s] + block + src[e+len(end):]
	if out == src {
		fmt.Printf("docsref: %s already current (%d entries)\n", t.path, n)
		return nil
	}
	if err := os.WriteFile(t.path, []byte(out), 0o644); err != nil {
		return err
	}
	fmt.Printf("docsref: wrote %d entries into %s\n", n, t.path)
	return nil
}

func renderPermissions() (string, int, error) {
	if err := permission.Validate(); err != nil {
		return "", 0, fmt.Errorf("registry is invalid, fix that before publishing it: %w", err)
	}
	groups, perms := permission.AllGroups(), permission.AllPermissions()
	if len(perms) == 0 {
		return "", 0, fmt.Errorf("registry is empty - the wiring import stopped pulling in the domain inits")
	}
	sort.Slice(groups, func(i, j int) bool {
		if groups[i].SortOrder != groups[j].SortOrder {
			return groups[i].SortOrder < groups[j].SortOrder
		}
		return groups[i].Name < groups[j].Name
	})
	byGroup := map[string][]permission.Definition{}
	for _, p := range perms {
		byGroup[p.Group] = append(byGroup[p.Group], p)
	}
	for g := range byGroup {
		list := byGroup[g]
		sort.Slice(list, func(i, j int) bool {
			if list[i].SortOrder != list[j].SortOrder {
				return list[i].SortOrder < list[j].SortOrder
			}
			return list[i].Slug < list[j].Slug
		})
	}
	var b strings.Builder
	fmt.Fprintf(&b, "%d permissions in %d groups.\n", len(perms), len(groups))
	for _, g := range groups {
		list := byGroup[g.Slug]
		if len(list) == 0 {
			continue
		}
		fmt.Fprintf(&b, "\n### %s\n\n| Slug | Grants |\n|---|---|\n", g.Name)
		for _, p := range list {
			// The name usually just restates the slug, so a written description replaces it
			grants := p.Name
			if d := strings.TrimSpace(p.Description); d != "" {
				grants = d
			}
			fmt.Fprintf(&b, "| `%s` | %s |\n", p.Slug, oneLine(grants))
		}
	}
	return strings.TrimRight(b.String(), "\n"), len(perms), nil
}

func renderWebhookEvents() (string, int, error) {
	defs := webhook.AllEvents()
	if len(defs) == 0 {
		return "", 0, fmt.Errorf("no webhook events registered - the wiring import stopped pulling in the domain inits")
	}
	// Grouped by the event name's domain prefix, which is also how the admin picker reads
	byDomain := map[string][]webhook.EventDefinition{}
	var syncCount int
	for _, d := range defs {
		if d.Kind == webhook.KindSync {
			syncCount++
		}
		domain := d.Type
		if i := strings.Index(d.Type, "."); i > 0 {
			domain = d.Type[:i]
		}
		byDomain[domain] = append(byDomain[domain], d)
	}
	domains := make([]string, 0, len(byDomain))
	for k := range byDomain {
		domains = append(domains, k)
	}
	sort.Strings(domains)

	var b strings.Builder
	fmt.Fprintf(&b, "%d event types - %d async, %d sync.\n", len(defs), len(defs)-syncCount, syncCount)
	for _, dom := range domains {
		list := byDomain[dom]
		sort.Slice(list, func(i, j int) bool { return list[i].Type < list[j].Type })
		fmt.Fprintf(&b, "\n### %s\n\n| Event | Kind | What it means |\n|---|---|---|\n", dom)
		for _, d := range list {
			desc := d.Description
			if desc == "" {
				desc = d.Name
			}
			fmt.Fprintf(&b, "| `%s` | %s | %s |\n", d.Type, d.Kind, oneLine(desc))
		}
	}
	return strings.TrimRight(b.String(), "\n"), len(defs), nil
}

func renderSettings() (string, int, error) {
	if err := config.Validate(); err != nil {
		return "", 0, fmt.Errorf("registry is invalid, fix that before publishing it: %w", err)
	}
	sections, groups, defs := config.AllSections(), config.AllGroups(), config.AllDefinitions()
	if len(defs) == 0 {
		return "", 0, fmt.Errorf("no settings registered - the wiring import stopped pulling in the domain inits")
	}
	sort.Slice(sections, func(i, j int) bool {
		if sections[i].SortOrder != sections[j].SortOrder {
			return sections[i].SortOrder < sections[j].SortOrder
		}
		return sections[i].Label < sections[j].Label
	})
	groupsBySection := map[string][]config.Group{}
	for _, g := range groups {
		groupsBySection[g.Section] = append(groupsBySection[g.Section], g)
	}
	for s := range groupsBySection {
		list := groupsBySection[s]
		sort.Slice(list, func(i, j int) bool {
			if list[i].SortOrder != list[j].SortOrder {
				return list[i].SortOrder < list[j].SortOrder
			}
			return list[i].Label < list[j].Label
		})
	}
	// Registration order inside a group is the admin's rendering order, so it's preserved
	defsByGroup := map[string][]config.Definition{}
	for _, d := range defs {
		parts := strings.Split(d.Path, "/")
		if len(parts) != 3 {
			continue
		}
		defsByGroup[parts[0]+"/"+parts[1]] = append(defsByGroup[parts[0]+"/"+parts[1]], d)
	}

	var b strings.Builder
	fmt.Fprintf(&b, "%d settings in %d sections.\n", len(defs), len(sections))
	for _, s := range sections {
		printed := false
		for _, g := range groupsBySection[s.Slug] {
			list := defsByGroup[s.Slug+"/"+g.Slug]
			if len(list) == 0 {
				continue
			}
			if !printed {
				fmt.Fprintf(&b, "\n### %s\n", s.Label)
				printed = true
			}
			fmt.Fprintf(&b, "\n**%s**\n\n| Path | What it does | Type | Scope | Public | Default |\n|---|---|---|---|---|---|\n", g.Label)
			for _, d := range list {
				// Public is worth a column rather than a footnote - it's the unauthenticated surface
				pub := ""
				if d.Public {
					pub = "yes"
				}
				fmt.Fprintf(&b, "| `%s` | %s | %s | %s | %s | %s |\n",
					d.Path, describeSetting(d), d.Type, effectiveScoping(d, g, s), pub, defaultCell(d))
			}
		}
	}
	return strings.TrimRight(b.String(), "\n"), len(defs), nil
}

// The registry description where one is written, else the label - which at least names the knob
// even when it doesn't explain it
func describeSetting(d config.Definition) string {
	if s := strings.TrimSpace(d.Description); s != "" {
		return oneLine(s)
	}
	return oneLine(d.Label)
}

// Field, then group, then section, then global - the same inheritance the resolver applies
func effectiveScoping(d config.Definition, g config.Group, s config.Section) string {
	for _, sc := range []config.Scoping{d.Scoping, g.Scoping, s.Scoping} {
		if sc != "" {
			return string(sc)
		}
	}
	return string(config.ScopingGlobal)
}

// A secret's default would be a credential, and an empty one reads better as a dash
func defaultCell(d config.Definition) string {
	if d.Type == config.TypeSecret {
		return "-"
	}
	v := strings.TrimSpace(d.Default)
	if v == "" {
		return "-"
	}
	if len(v) > 40 {
		v = v[:37] + "…"
	}
	return "`" + oneLine(v) + "`"
}

// Table cells can't hold newlines or bare pipes
func oneLine(s string) string {
	s = strings.ReplaceAll(s, "\n", " ")
	s = strings.ReplaceAll(s, "|", "\\|")
	return strings.Join(strings.Fields(s), " ")
}
